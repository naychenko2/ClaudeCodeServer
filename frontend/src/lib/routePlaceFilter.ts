// Фильтр маршрутов пикера «Поставщики моделей» по месту (ADR-027 §2).
//
// Места каталога делятся на текстовые (Input = Text) и с картинками на входе
// (Input = Images, разметка фото персонажа). Для мест с картинками большая часть
// маршрутов не годится: локальная текстовая модель зрения не имеет, direct:-модели
// картинок не передают, пресеты — текстовые цепочки, и модели без зрения «тихо
// отвечают, не видя картинки». Поэтому пикер на таких местах показывает только
// vision-модели, а на месте ракурса — ещё и пункт «Локально, InsightFace» (face-pose).
//
// Чистая функция: не знает ни React, ни сторов, ни каталога моделей. Признак зрения
// (hasVision) считает вызывающий — у него есть каталог моделей и caps провайдеров;
// функция лишь фильтрует по уже готовому признаку. Это держит мутации простыми:
// «место с картинками — без маршрутов без зрения», «face-pose только у ракурса»,
// «обычное место — список без изменений».

// Контекст места: что на вход и умеет ли считать ракурс лица локально.
export interface PlaceRouteContext {
  input: 'text' | 'images';
  facePose: boolean;
}

// Кандидат маршрута в пикере: его значение и видит ли он картинки.
export interface RouteCandidate {
  route: string;
  hasVision: boolean;
}

// Маршрут face-pose: не-LLM исполнитель (InsightFace), виден только на месте ракурса.
export const FACE_POSE_ROUTE = 'face-pose';

// Какие маршруты показать пикеру для этого места:
//  - место с картинками: маршруты без зрения вырезаются;
//  - место ракурса (facePose) среди мест с картинками: добавляется пункт face-pose;
//  - обычное место: список без изменений.
export function filterPlaceRoutes(ctx: PlaceRouteContext, candidates: RouteCandidate[]): RouteCandidate[] {
  if (ctx.input === 'images') {
    const kept = candidates.filter(c => c.hasVision);
    return ctx.facePose ? [...kept, { route: FACE_POSE_ROUTE, hasVision: true }] : kept;
  }
  return candidates;
}
