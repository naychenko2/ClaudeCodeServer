using ClaudeHomeServer.Models;
using FluentAssertions;

namespace ClaudeHomeServer.Tests.Services;

// Формула «сколько добавить к потолку, чтобы покрыть план» — TeamImplementBudget.PlanShortfall.
//
// Как было на самом деле (фикс-волна 4 поправила враньё прежнего комментария, который
// излагал несуществующую историю про разъехавшиеся числа): дефект c156193b лечился
// коммитом 0ffaf081 на фронте — плашка показывала как новый потолок РАЗМЕР ПЛАНА
// («поднимется до N» при плане на N волн), хотя расширение в TeamDecisionService всегда
// считало Max + max(0, plan - left). Тем же коммитом появилась FillAfterBudgetAsync —
// сразу с формулой, тождественной той, что стояла в TeamDecisionService. То есть две
// точки НЕ расходились в числах ни дня; расходилось «обещание в тексте плашки» и
// «поведение при запуске». Коммит 9fe784ab — тождественный рефакторинг: одинаковое
// выражение из двух мест сведено в один метод, чтобы копии не разошлись потом.
//
// Этот набор сторожит саму формулу. Связь «плашка бюджета считает ТОЙ ЖЕ формулой»
// сторожится отдельно, бэкенд-тестом через FillAfterBudgetAsync с ненулевым расходом —
// TeamWaveServiceTests.ПлашкаБюджета_НенулевойРасход_ПотолкиСчитаютсяОтОстатка (M7):
// одного покрытия статического хелпера для этого мало, подмена вызова на формулу без
// учёта расхода оставалась зелёной.
public class TeamImplementBudgetTests
{
    [Fact]
    public void PlanShortfall_НулевойРасходВозвращаетРазницуПланМинусОстаток()
    {
        // Свежий бюджет, WavesUsed=0, план шире потолка — дельта строго равна дефициту.
        // Это и есть «план сверх остатка»: при нулевом расходе остаток равен потолку.
        TeamImplementBudget.PlanShortfall(max: 2, used: 0, plan: 5)
            .Should().Be(3, "план шире потолка на 3 — дельта = 3");
    }

    [Fact]
    public void PlanShortfall_НенулевойРасходУчитывается()
    {
        // Сценарий из находки c156193b: MaxWaves=2, WavesUsed=1, план на 2 волны. Плашка
        // обещала «потолок поднимется до 2» (брала размер плана), а запуск поднимал его
        // до 3 — расход волны 1 в обещании не учитывался. Правильная дельта здесь 1:
        // остаток 2-1=1, плану нужно 2. Это единственный кейс набора, который отличает
        // формулу «от остатка» от формулы «от потолка» — с нулевым расходом они совпадают.
        TeamImplementBudget.PlanShortfall(max: 2, used: 1, plan: 2)
            .Should().Be(1, "остаток 1, план 2 — дефицит 1 (находка дефекта c156193b)");
    }

    [Fact]
    public void PlanShortfall_ПланУжеУкладываетсяВозвращаетНоль()
    {
        // План короче остатка — расширять нечего. Защита от обратного хода (плашка бы
        // показала отрицательную дельту без max(0, …)).
        TeamImplementBudget.PlanShortfall(max: 10, used: 5, plan: 3)
            .Should().Be(0, "план уже укладывается в остаток 5 — расширение 0");
    }

    [Fact]
    public void PlanShortfall_ОстатокРовноРавенПлануВозвращаетНоль()
    {
        // Граница: остаток и план совпали — добавлять нечего, но и не уменьшать.
        TeamImplementBudget.PlanShortfall(max: 4, used: 1, plan: 3)
            .Should().Be(0, "остаток 3 = план 3 — дельта 0");
    }

    [Fact]
    public void PlanShortfall_ОтрицательныйОстатокЗащищаетсяНижнимНулем()
    {
        // Легаси-сессия без реинициализации счётчиков: used > max (счётчик «израсходовано»
        // мог перегнать потолок при ручных правках). Без max(0, max - used) ушла бы
        // отрицательная дельта, а Max += delta уехала бы в минус и тихо сломала
        // арифметику.
        TeamImplementBudget.PlanShortfall(max: 2, used: 5, plan: 10)
            .Should().Be(10, "остаток защищён нулём, дельта = весь план");
    }

    [Fact]
    public void PlanShortfall_НулевойПланВозвращаетНоль()
    {
        // Плана нет (плашка бюджета скрывается, потолки не двигаются). Защита от
        // отрицательной дельты при пустом плане.
        TeamImplementBudget.PlanShortfall(max: 4, used: 0, plan: 0)
            .Should().Be(0);
        TeamImplementBudget.PlanShortfall(max: 4, used: 2, plan: 0)
            .Should().Be(0);
    }
}
