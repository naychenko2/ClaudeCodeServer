// Markdown → плоский текст в одну строку.
//
// Нужен для свёрнутых превью (обрезка через -webkit-line-clamp): кламп работает только
// со строчным текстом, блочные <p>/<ul>/<pre> отрендеренного markdown ломают обрезку.
// Модуль намеренно чистый (без React и DOM) — тестируется vitest в окружении node.
//
// Это НЕ замена docsLinks.stripMarkdown: там контракт слагификации якорей с бэкендом
// (DocsIndexService.Slugify), у него другие правила и трогать его нельзя.
export function markdownToPlain(text: string): string {
  if (!text) return '';
  return text
    // Рамки код-фенсов убираем, содержимое остаётся обычным текстом
    .replace(/^[ \t]*(?:```|~~~).*$/gm, '')
    // Начало строки: заголовки ATX, цитаты, маркеры списков, горизонтальные линейки
    .replace(/^[ \t]*#{1,6}[ \t]+/gm, '')
    .replace(/^[ \t]*>[ \t]?/gm, '')
    .replace(/^[ \t]*(?:-{3,}|\*{3,}|_{3,})[ \t]*$/gm, '')
    .replace(/^[ \t]*(?:[-*+]|\d+[.)])[ \t]+/gm, '')
    // Картинки и ссылки — только подпись
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    // Инлайн-код и выделение; одиночное «_» снимаем только по краям слова,
    // иначе разрежет snake_case-идентификаторы
    .replace(/`+/g, '')
    .replace(/\*\*|__|~~/g, '')
    .replace(/\*([^*\n]+)\*/g, '$1')
    .replace(/(^|[^\p{L}\p{N}_])_([^_\n]+)_(?=[^\p{L}\p{N}_]|$)/gu, '$1$2')
    // Всё в одну строку
    .replace(/\s+/g, ' ')
    .trim();
}
