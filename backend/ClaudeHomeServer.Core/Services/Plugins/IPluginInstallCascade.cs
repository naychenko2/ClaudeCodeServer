namespace ClaudeHomeServer.Services.Plugins;

// Шов «внешние ссылки на установку плагина» (ADR-031 §2.4, §4, шаг 1.4).
//
// Каскад удаления установки (PluginUninstall) снимает всё, что живёт в хранилище
// владельца (пакет, запись installed.json, черновики, выданные права, секреты), а
// «внешние» ссылки — привязки персон (Skill-биндинг plugin:{id}) и размещения панелей
// в слотах — живут в других вертикалях. По правилу вертикалей (ADR-014) Plugins не
// ссылается на них напрямую: их снимает этот шов, реализацию регистрирует подсистема
// (MVP — no-op, реальный адаптер — после UI-шага 2.x, когда биндинги/слоты создаются).
//
// Направление: Plugins -> Core <- (Notes/Tasks/Personas). Вызывается один раз на
// uninstall, после того как запись установки уже удалена из стора.
public interface IPluginInstallCascade
{
    // Снять внешние ссылки на установку плагина <paramref name="pluginId"/> владельца
    // <paramref name="ownerId"/>: привязки персон (plugin:{id}) и размещения в слотах.
    void OnUninstalled(string ownerId, string pluginId);
}
