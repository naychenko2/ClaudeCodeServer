using ClaudeHomeServer.Models;

namespace ClaudeHomeServer.Services;

// Шов PersonaManager (Этап 5, вынос Spend). Spend использует только
// `GetByIdInternal` — резолв персоны по id для отображения имени в pivot-узлах
// и паспорте хода (формат «Role (Name)»). Внешний `GetById` отфильтровывает
// неактивные персоны; Spend интересуют ВСЕ, включая архивные, поэтому берём
// именно `GetByIdInternal` — обращение напрямую к словарю реестра, минуя
// проверки доступа. Полный PersonaManager не нужен.
// НЕ дубль `IPersonaDirectory` (там `GetByOwner` + `Delete`): тот обслуживает
// каскад жизненного цикла владельца (Knowledge чистит персоны при удалении
// пользователя), этот — точечное чтение по id для отчётов трат. Склейка дала бы
// читающему потребителю доступ к `Delete`, то есть расширила бы права ради
// экономии одного файла. Разделение осознанное — проверено при выносе Spend.
//
// Этап 5 (сцепка Memory + Dossiers): добавлен `GetAllInternal` —
// PersonaMemoryConsolidationService обходит ВСЕ персоны для полной проходки
// консолидации (без ownerId: тик раз в ConsolidateIntervalHours). Это не каскад
// жизненного цикла (Directory) и не точечный резолв (Resolver) — это «полный
// обход внутреннего реестра». Остаётся в Lookup, поскольку семантика та же:
// чтение внутреннего словаря, минуя проверки доступа. Расширение, а не новый
// шов: держать два интерфейса про «чтение реестра персон» — путь к дубли,
// который мы уже ловили на Spend.
public interface IPersonaLookup
{
    // Возвращает персону по id или null, если такой нет. Доступ не проверяется —
    // это чтение внутреннего реестра, а не публичный API персон.
    Persona? GetByIdInternal(string id);

    // Полный список всех персон внутреннего реестра. Доступ не проверяется.
    // Используется фоновым проходом консолидатора памяти персон, который
    // обходит все записи независимо от владельца. Внешним сервисам не
    // показывается: наружу персоны идут через `IPersonaDirectory.GetByOwner`.
    IReadOnlyCollection<Persona> GetAllInternal();
}
