namespace ClaudeHomeServer.Models;

// Внешний доступ к дев-серверу проекта: отдельный поддомен, на котором сайт видит себя
// в КОРНЕ, а не под путём.
//
// Зачем отдельный хост, если есть панель «Сервисы» с прокси /preview/{projectId}/**.
// Тот прокси срезает префикс, и дев-сервер думает, что живёт в корне, — но браузер-то
// грузит страницу с адреса с префиксом. Любая абсолютная ссылка в разметке («/assets/app.js»,
// «/@vite/client», рантайм-загрузка Module Federation) уходит в корень ПРОДУКТА и получает
// 404. Переписать это на лету нельзя: пути строятся в том числе в JS во время работы.
//
// Защита — конфигурация, а не отсутствие кода: файл уезжает всем, у кого свой инстанс,
// поэтому Enabled по умолчанию false, а реальные значения живут в машинном
// appsettings.Local.json вне git (тот же приём, что у TrayDeployOptions).
public class ExternalPreviewOptions
{
    public const string Section = "ExternalPreview";

    // Главный рубильник — и это именно KILL SWITCH, а не «перестать выдавать новые ссылки»:
    // при false поддомен отвечает 404 на ВСЁ, включая уже открытые сессии. Иначе «выключить
    // фичу» не выключало бы доступ к машине снаружи, то есть не делало бы того, ради чего
    // рубильник и нужен.
    public bool Enabled { get; set; }

    // Публичный адрес поддомена ЦЕЛИКОМ: схема, хост и порт — «https://svc.example.me:8080».
    //
    // Порт обязателен, когда он не стандартный. Собрать адрес из одного имени хоста нельзя:
    // Kestrel может слушать один порт, а наружу проброшен другой, и ссылка «https://имя/»
    // увела бы браузер на 443 — к чужому сайту. Гадать тут нечем, поэтому адрес задаётся
    // целиком и берётся как есть.
    public string PublicBaseUrl { get; set; } = "";

    // Срок жизни выданной ссылки. Дальше она мертва, даже если реестр её ещё помнит.
    public int TokenLifetimeHours { get; set; } = 12;

    /// <summary>
    /// Имя хоста, по которому middleware узнаёт «свои» запросы. ВЫВОДИТСЯ из PublicBaseUrl,
    /// отдельной настройки нет намеренно: два источника одной правды рано или поздно
    /// разъезжаются правкой одного из них, и получается неисправность, которую не видно
    /// ни в одном из двух мест.
    /// </summary>
    public string? Host =>
        Uri.TryCreate(PublicBaseUrl, UriKind.Absolute, out var uri) && !string.IsNullOrEmpty(uri.Host)
            ? uri.Host
            : null;

    /// <summary>Настройки достаточно, чтобы фича могла работать (адрес разобрался).</summary>
    public bool IsConfigured => Host is not null;
}
