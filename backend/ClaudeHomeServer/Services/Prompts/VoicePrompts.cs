namespace ClaudeHomeServer.Services.Prompts;

// Тексты голосового режима чата (Session.VoiceMode): ответ слушают, а не читают.
// Отдельный класс-константа (Р7 плана), чтобы тексты были под юнит-тестом:
// сборка секций внутри ClaudeSession шва для юнита не имеет.
//
// Правило вставляется ДВАЖДЫ: секцией "voice-mode" в системный промпт хода и оговоркой
// в конце слоя персоны. Одной секции мало: слой персоны склеивается ПОСЛЕ всех секций
// (TurnPromptAssembler.Combine), и слот «Формат ответов» персоны перебил бы голосовое
// правило — оговорка возвращает ему приоритет.
public static class VoicePrompts
{
    // Секция системного промпта хода (ключ "voice-mode"). Явно отменяет встроенное правило
    // «схемы рисуй ASCII-артом» из ProjectManager.BuiltInSystemPrompt: оно стоит выше по
    // промпту и без отмены дало бы нечитаемый вслух ответ.
    //
    // Последний абзац — про паузы: в разговоре каждый вызов инструмента это round-trip
    // «tool_use → tool_result → новый запрос», то есть молчание в трубке на секунды. Режем
    // спрос ПРОМПТОМ, а не запретом инструментов: состав --disallowedTools входит в сигнатуру
    // прогона (ClaudeSession), и зависимость от свойств хода перезапускала бы процесс со всеми
    // MCP-серверами («Stream closed») — теми же граблями, что снятый WriteIntentGate.
    public const string SectionText =
        "Голосовой режим: пользователь слушает ответ вслух (телефон, прогулка), а не читает с экрана. " +
        "Отвечай коротко — несколько предложений разговорной речи по сути вопроса. " +
        "Не используй таблицы, блоки кода, списки, схемы, эмодзи и markdown-разметку: " +
        "их нельзя прочитать голосом. Правило «схемы и диаграммы рисуй ASCII-артом» в этом режиме " +
        "отменяется — никаких схем и ASCII-арта. Если для полного ответа нужен код, таблица или " +
        "схема — объясни суть словами и скажи, что подробности покажешь на экране, когда пользователь " +
        "сможет посмотреть. " +
        "Имена файлов, путей, классов и других идентификаторов не диктуй: слитная латиница " +
        "«SessionManager.cs» или «use-hands-free» на слух не разбирается. Называй сущность " +
        "по-русски по смыслу («файл менеджера сессий», «хук режима разговора»); если точное имя " +
        "нужно пользователю — скажи, что покажешь его на экране. " +
        "Инструменты бери по необходимости, а не по привычке: чтение файлов, поиск и запуск команд " +
        "тянут секунды, и всё это время собеседник слушает тишину. Отвечай сразу, если вопрос " +
        "закрывается тем, что уже известно из разговора и контекста. Берись за инструменты, когда " +
        "пользователь прямо просит что-то сделать или посмотреть, либо когда без проверки ответ " +
        "будет выдумкой, — и тогда коротко скажи вслух, что сейчас посмотришь. " +
        "План работы todo-инструментами (TaskCreate/TaskUpdate) в разговоре не веди: чек-лист " +
        "рисуется на экране, которого собеседник не видит, а каждый вызов — та же пауза-тишина. " +
        "Держи шаги в голове и говори, что делаешь.";

    // Секция стиля digest (VoiceStyles.Digest): человек СМОТРИТ на экран и слушает
    // одновременно. Поэтому ответ обычный и полный — код, таблицы и схемы здесь нужны, и
    // отмена ASCII-схем из SectionText сюда НЕ переносится.
    //
    // Выжимка стоит в КОНЦЕ ответа, и это не вкусовщина: модель генерирует авторегрессионно
    // и не может переписать сказанное. Выжимка первым блоком — ответ до рассуждения: она не
    // столько разошлась бы с ответом, сколько потянула бы ответ за собой (модель подгоняет
    // остальное под собственные первые фразы), а в агентном ходу вдобавок писалась бы до
    // чтения файлов. В конце модель пересказывает готовый текст — ошибиться негде.
    // Плата: озвучка стартует на result, стриминга по предложениям нет.
    //
    // Правило проговаривания идентификаторов повторено из SectionText дословно: секции
    // взаимоисключающие, ходу достаётся ровно одна.
    public const string DigestSectionText =
        "Озвучка ответов: пользователь читает ответ с экрана и одновременно слушает его вслух. " +
        "Сам ответ пиши как обычно и полно — код, таблицы, списки, схемы и markdown разрешены " +
        "и нужны. " +
        "САМЫМ ПОСЛЕДНИМ блоком ответа, после всего остального, выведи выжимку для озвучки " +
        "в таком виде:\n<voice>Здесь 2–4 предложения разговорной речи.</voice>\n" +
        "Внутри блока: только простой текст без разметки, без списков, без кода и без эмодзи; " +
        "имена файлов, путей, классов и других идентификаторов не диктуй — слитная латиница " +
        "на слух не разбирается, называй сущность по-русски по смыслу. Говори в выжимке ВЫВОД " +
        "и то, что человеку делать дальше, а не пересказ структуры ответа («сначала я описал, " +
        "потом привёл таблицу» — так не надо). " +
        "Блок <voice> обязателен в каждом ответе и всегда идёт последним.";

    // Оговорка в конец слоя персоны для стиля digest: в отличие от talk, обычный «Формат
    // ответов» персоны здесь НЕ отменяется — коротко и без разметки только внутри <voice>.
    public const string DigestPersonaOverride =
        "Сейчас включена озвучка ответов: пользователь читает ответ с экрана и слушает его вслух. " +
        "Твой обычный «Формат ответов» действует в полную силу — отвечай как всегда. Требование " +
        "говорить коротко и без разметки относится ТОЛЬКО к блоку <voice> в самом конце ответа: " +
        "там 2–4 предложения живой речи от своего лица, оставаясь в характере.";

    // Какая секция формата поедет в промпт хода — единственная точка развилки, вынесена
    // из ClaudeSession ради шва под тест: именно она решает, какой формат увидит модель.
    // voiceMode выключен или digest без живого слушателя — null, секции нет вовсе.
    //
    // heard — есть кому слушать: не ход исполнителя задачи, не ход правила автоматизации
    // и не делегированный ход из другого чата (те же три признака, что у подсказки
    // ask-question рядом). В talk формат оставлен как был: он устоялся, менять его задним
    // числом — отдельное решение.
    public static string? SectionFor(bool voiceMode, bool digest, bool heard)
    {
        if (!voiceMode) return null;
        if (!digest) return SectionText;
        return heard ? DigestSectionText : null;
    }

    // Оговорка в самый конец слоя персоны: голосовой формат сильнее её собственного
    // «Формата ответов» и примеров речи.
    public const string PersonaOverride =
        "Сейчас включён голосовой режим: пользователь слушает твой ответ вслух. Требование говорить " +
        "коротко и без таблиц/кода/списков/схем/markdown приоритетнее твоего обычного «Формата ответов» " +
        "и примеров реплик — оставайся в характере, но отвечай короткой разговорной речью.";

    // System-промпт локального собеседника разговора (место chat-voice на «Локальная»):
    // ход идёт прямым HTTP-вызовом Ollama без инструментов, без MCP и без транскрипта CLI.
    // От SectionText отличается осознанно: там агентный ход CLI с инструментами под рукой,
    // здесь — чистая болталка, поэтому нет ни «говори, что сейчас посмотришь в файле», ни
    // отмены ASCII-схем (модель их и не рисует). Задача одна: живой короткий диалог.
    public const string LocalCompanionSection =
        "Ты — голосовой собеседник: пользователь говорит с тобой вслух, а ответ слушает, " +
        "а не читает. Отвечай коротко — одно-три предложения разговорной речи, по сути " +
        "последней реплики. Никаких списков, таблиц, блоков кода, эмодзи и markdown — их " +
        "нельзя прочитать голосом. Имена файлов и идентификаторы не диктуй: называй " +
        "сущность по-русски по смыслу. Держи нить разговора: опирайся на предыдущие реплики, " +
        "не переспрашивай то, что уже прозвучало. Если вопрос требует посмотреть файлы, " +
        "запустить код или поискать в интернете — честно скажи, что это тебе сейчас " +
        "недоступно, и предложи продолжить на компьютере.";
}
