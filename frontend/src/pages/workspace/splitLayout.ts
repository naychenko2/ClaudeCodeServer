// Раскладка «чат | файл» в центре: сколько места нужно, чтобы файл открылся рядом с чатом

// Ленте чата в разделённом центре уже этой ширины композер не вмещает: кнопки режимов и голоса съедают строку,
// поле ввода сжимается до слова. Это минимум колонки, а не желаемая ширина
export const CHAT_SPLIT_MIN_PX = 400;
// Минимум колонки-соседки (файла, задачи, ридера)
export const SPLIT_SIDE_MIN_PX = 200;
// Уже этой ширины колонке чата делать нечего: композер и полоса «Видео» не читаются (меньше — файл во весь центр)
export const CHAT_SPLIT_FLOOR_PX = 320;

// Влезает ли файл рядом с чатом в центре шириной centerW: соседке отдаётся её минимум, остальное — чату.
// 0 — ширина ещё не замерена: считаем, что влезает, чтобы не мигать раскладкой при первом кадре
export const canSplitCenter = (centerW: number): boolean =>
  centerW <= 0 || centerW - SPLIT_SIDE_MIN_PX >= CHAT_SPLIT_FLOOR_PX;
