import { useState } from 'react';
import { C, FONT } from '../../lib/design';
import { RailFlyout } from './RailFlyout';
import { RAIL_W } from './RailCapsule';

// Шляпка рельсы — микро-подпись у верхней кромки капсулы: чья это рельсина.
// У края окна капсул стоит стопка (рельса панелей, док проектов, док «Стены»),
// оправа у всех общая (RailCapsule), и различить их можно было только по
// содержимому — то есть по столбику одинаковых 32px-иконок.
//
// Подпись, а не иконка-эмблема: в 40px-полосе эмблема встала бы В РЯД с кнопками
// панелей и читалась бы как ещё одна кнопка (только неактивная). Текст такой роли
// на себя не берёт — его не с чем спутать.
//
// Регистр — капс, кегль 6. Тон — smoke, самый тихий нейтральный: шляпка это
// ярлык, а не элемент управления, и не должна спорить за внимание ни с иконками
// под ней, ни с их подписями. Текстовые токены (даже textMuted) для неё слишком
// контрастны — на 40px-полосе подпись начинала читаться как заголовок.
//
// Ширина проверена замером, а не на глаз: внутри капсулы 39px, а капс Hanken
// Grotesk шире, чем кажется — «Панели» на 9px даёт 39.9px и уже не влезает,
// «Проекты» — 47.3px. Ширина линейна по кеглю: на 6px те же слова дают ~27 и ~32,
// то есть запас есть даже у семибуквенного слова.

// Сколько высоты капсулы съедает шляпка вместе со своей чертой и зазором до
// первой кнопки. Нужна тем, кто считает вместимость капсулы по высоте окна
// (док проектов — число слотов под иконки; рельса панелей — резерв места под
// схлопнутую капсулу).
export const RAIL_HAT_H = 16;

// Черта под подписью — во всю ширину капсулы, от кромки до кромки. Собственная,
// а не RailSep: тот держит ширину 22 и отделяет наборы кнопок ВНУТРИ столбца,
// здесь же граница другого рода — «выше ярлык, ниже сама рельса», и во всю
// ширину она не путается со служебными чертами столбца.
function HatRule() {
  return <div style={{ alignSelf: 'stretch', height: 1, background: C.border, flexShrink: 0 }} />;
}

export function RailHat({ side, label, title }: {
  // Сторона окна: в неё же выезжает плашка с полным названием
  side: 'left' | 'right';
  // Подпись в самой шляпке — капс до семи символов (см. замер выше)
  label: string;
  // Полное название рельсы для плашки по наведению. Шести-семи букв капса на
  // объяснение не хватает, а плашка — та же, что подписывает кнопки рельсы, и
  // места в ней сколько угодно. Не задано — плашки нет вовсе.
  title?: string;
}) {
  const [hover, setHover] = useState(false);

  const hat = (
    <div
      onMouseEnter={() => setHover(true)}
      onMouseLeave={() => setHover(false)}
      style={{
        display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 2,
        // Ширина именно 100%, а не alignSelf: stretch: с плашкой шляпка живёт внутри
        // якоря RailFlyout (строчный flex), и растягиваться ей надо по нему
        width: '100%', flexShrink: 0, userSelect: 'none',
      }}
    >
      <div style={{
        fontFamily: FONT.sans, fontSize: 6, fontWeight: 700, lineHeight: '7px',
        letterSpacing: '0.03em', textTransform: 'uppercase',
        // Под курсором ярлык оживает: в покое он почти растворён (smoke), и без
        // отклика непонятно, что на него вообще можно навести
        color: hover ? C.textMuted : C.smoke,
        transition: 'color 0.12s',
        whiteSpace: 'nowrap',
      }}>
        {label}
      </div>
      <HatRule />
    </div>
  );

  if (!title) return hat;

  // Плашка выезжает из-под капсулы напротив шляпки — тем же язычком, что
  // подписывает кнопки рельсы
  return (
    <RailFlyout
      side={side}
      label={title}
      open={hover}
      railWidth={RAIL_W}
      hostStyle={{ alignSelf: 'stretch' }}
      // Таблетка со скруглениями с обеих сторон: подпись рельсы — не язычок кнопки
      standalone
    >
      {hat}
    </RailFlyout>
  );
}
