// Человекочитаемые названия ключей палитры AGENT_COLORS для фона проекта. Подставляются
// в подпись «Цвет — <название>» и в диалог подтверждения смены цвета. Согласованы с
// продактом (Софья): предметный стиль (материал/природа), green→«изумрудный» и cyan→
// «морской» — из макета/спеки, остальные подобраны в том же стиле. Источник правды по
// текстам интерфейса фичи — docs/features/project-backgrounds.md.
export const BACKGROUND_COLOR_NAMES: Record<string, string> = {
  yellow: 'янтарный',
  orange: 'терракотовый',
  blue: 'стальной',
  green: 'изумрудный',
  purple: 'сливовый',
  red: 'кирпичный',
  brown: 'кофейный',
  cyan: 'морской',
  pink: 'маджента',
};

// Название цвета по ключу палитры; неизвестный ключ — заглушка (не должен случаться:
// бэк принимает только девять ключей AGENT_COLORS, ADR-008 §2.2).
export function backgroundColorName(key: string | null | undefined): string {
  return (key && BACKGROUND_COLOR_NAMES[key]) ?? 'цвет не определён';
}
