// Подписи корня дерева файлов. У ПРОЕКТА корень — это корень проекта, у личной
// панели (папка «Личного») — сама папка «Личное»: слово «проект» человеку в
// личном чате показывать нельзя, проекта у него нет.
//
// Подписи живут здесь, а не внутри FileExplorer, потому что их читают и
// FileExplorer (подвал меню «Новый», диалоги создания, список папок для
// переноса), и тест личной панели — без рендера дерева.

export interface FileRootLabels {
  // Подпись корня в подвале меню «Новый» и в списке папок для переноса
  short: string;
  // Подзаголовок диалогов создания («Новый файл» / «Новая папка» / «Новая диаграмма»)
  inRoot: string;
  // Подсказка кнопки «в корень» в подвале меню «Новый»
  inRootAction: string;
  // Подпись корня в списке папок для переноса
  list: string;
  // Заголовок пустого состояния дерева («Проект пуст» / «Личное пусто»)
  emptyTitle: string;
  // Подсказка под заголовком пустого состояния
  emptyHint: string;
  // Заголовок подсказки про файлы в пустом состоянии
  filesTipTitle: string;
  // Текст подсказки про файлы в пустом состоянии
  filesTipText: string;
}

