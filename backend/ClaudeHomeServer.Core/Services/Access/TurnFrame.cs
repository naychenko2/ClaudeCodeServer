using ClaudeHomeServer.Models;

namespace ClaudeHomeServer.Services.Access;

/// <summary>
/// Рамка хода — сколько личного пространства арендатора открыто агенту (разрез §И.3).
/// </summary>
public enum TurnFrameKind
{
    /// <summary>Всё личное пространство арендатора: личный проект и — с S2d-1b — приватный чат владельца
    /// в общем проекте при акторе-владельце.</summary>
    Wide,
    /// <summary>Только контекст этого проекта: любой общий чат общего проекта — для любого участника,
    /// включая владельца (решение 29.10), и приватный чат редактора: его личное пространство под токеном
    /// арендатора недостижимо в принципе (ограничение, в плашку).</summary>
    Narrow,
}

/// <summary>
/// Рамка хода (S2a-2, разрез §И.3 в редакции решения Андрея 29.10) — чистая функция над моделью,
/// по образцу <see cref="ProjectAccess"/>: без I/O и без зависимостей от Main. Ход участника идёт с
/// сервисным токеном арендатора, и без рамки агент участника получил бы всё личное пространство
/// владельца (<c>WorkspaceToolset</c>, подборка в ход). Вызывающие шаги (S2a-3…S2a-4) сужают по
/// вердикту платформенные тулсеты и подборку; здесь — только вердикт.
/// Решение 29.10: в чате общего проекта личное пространство арендатора (настройки, заметки, память)
/// не подмешивается НИКОМУ из участников, включая самого владельца. Раньше широкая рамка
/// сохранялась за владельцем (редакция разреза 28.10); теперь она остаётся только за личным проектом
/// и, с S2d-1b, за приватным чатом владельца в общем проекте при акторе-владельце (находка 4
/// разреза S2d: рамка открывает личное пространство арендатора, поэтому приватный чат редактора
/// остаётся узким).
/// </summary>
public static class TurnFrame
{
    /// <summary>
    /// Рамка хода в проекте. Общий проект (у него есть участники, <c>Project.Members</c>, S1-1) —
    /// <see cref="TurnFrameKind.Narrow"/> при любом акторе: у участника, у самого арендатора в общем
    /// чате (решение 29.10) и при акторе неизвестном (fail-closed: фоновое действие или исполнитель
    /// без инициатора не получает личное пространство владельца). Единственное исключание —
    /// приватный чат владельца при акторе-владельце, см. <paramref name="session"/>. Личный проект —
    /// <see cref="TurnFrameKind.Wide"/>: чужих участников у него нет (доступ к нему даёт только
    /// владение, <see cref="ProjectAccess.Check"/>), поэтому защищать не от чего — всё пространство
    /// и так принадлежит арендатору. null-проект общим быть не может (общий всегда с участниками)
    /// и относится к личным.
    /// Инвариант: Wide — только при известном арендаторе. Пустой <paramref name="tenantOwnerId"/>
    /// означает «чьё личное пространство открывать» — не определено, поэтому в обеих ветках
    /// Narrow (fail-closed, как в редакции до решения 29.10).
    /// </summary>
    /// <param name="session">Чат хода. В общем проекте широкая рамка дозволена только приватному чату
    /// владельца при акторе-владельце: <c>PrivateToUserId == tenantOwnerId</c> и
    /// <c>actorUserId == tenantOwnerId</c> (<see cref="Session.PrivateToUserId"/>, S2d-1; находка 4
    /// разреза S2d: рамка открывает личное пространство АРЕНДАТОРА — в приватном чате редактора она
    /// отдала бы ему всё личное владельца). Приватный чат редактора остаётся Narrow: его личное
    /// пространство под токеном арендатора недостижимо в принципе (ограничение, в плашку). Общий
    /// чат общего проекта — Narrow всем, включая владельца (решение 29.10).</param>
    /// <param name="tenantOwnerId">Арендатор проекта — чьё личное пространство рамка закрывает;
    /// null/пусто — арендатор неизвестен, Wide при этом невозможен (см. <see cref="Resolve"/>).</param>
    /// <param name="actorUserId">Инициатор хода (<c>ActorUserId</c> реестра, S2a-1); null/пусто —
    /// инициатор неизвестен.</param>
    public static TurnFrameKind Resolve(Project? project, Session? session, string? tenantOwnerId, string? actorUserId)
    {
        // Wide открывает личное пространство арендатора; при неизвестном арендаторе — чьё оно,
        // не определено: Narrow в обеих ветках (fail-closed).
        if (string.IsNullOrEmpty(tenantOwnerId))
            return TurnFrameKind.Narrow;

        // Личный проект: своих участников нет, личное пространство и так открыто своему владельцу.
        if (!IsSharedProject(project))
            return TurnFrameKind.Wide;

        // Общий проект: Wide — только приватный чат владельца при акторе-владельце: рамка открывает
        // личное пространство арендатора, и оно принадлежит владельцу. Приватный чат редактора —
        // Narrow: его личное пространство под токеном арендатора недостижимо (ограничение, в плашку).
        // Общий чат — Narrow всем, включая владельца (решение 29.10); актор неизвестен — Narrow
        // (fail-closed). null-чат или чат без признака приватности (PrivateToUserId null) — общий.
        if (session?.PrivateToUserId == tenantOwnerId && actorUserId == tenantOwnerId)
            return TurnFrameKind.Wide;

        return TurnFrameKind.Narrow;
    }

    /// <summary>Общий проект — с непустым списком участников; пустой список нормализован в null (Project.Members).</summary>
    private static bool IsSharedProject(Project? project) => project?.Members is { Count: > 0 };
}
