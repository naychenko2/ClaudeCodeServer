// Ручки, отдающей содержимое .md, в бэке ещё нет: единственная транскрипционная ручка —
// снимок (LocalModelStatsController, GET /api/local-model/transcription), а тот отдаёт
// mdPath строкой — путём на worker'е, не телом файла. Клиент этот путь в URL не превращает:
// абсолютный путь чужого узла нельзя ни показать, ни отдать бэку «как есть» — это обход
