namespace ClaudeHomeServer.Services.Prompts;

// Тексты детского слоя (ADR-041, разрез docs/research/kids-mode-wave1-cut-2026-11.md §4
// «Возрастной промпт безопасности», план KM-B6c): правила тьютора детского чата.
//
// Ставятся у ДЕТСКОГО хода всегда и независимо от персоны: держит их признак ребёнка
// (IChildModePolicy), а не текст тьютора — тьютора выбирает админ, и его характер может быть
// любым. Отдельный класс-константа (тот же приём, что у VoicePrompts): тексты под юнит-тестом,
// а не внутри сборки слоя.
//
// Две точки, по образцу голосового формата (VoicePrompts + PersonaPromptBuilder): секция
// внутри слоя персоны и короткая оговорка его последним блоком. Одной секции мало: слоты
// «Формат ответов» и примеры речи стоят ниже по слою и перебили бы правило — оговорка
// возвращает ему приоритет.
//
// Имя и класс — из плана волны 1 (один ребёнок); предметы — нейтральной строкой: репетитор
// ведёт предметы профиля ребёнка, а не назанный перечень, и подстановка названия предмета
// сделала бы секцию зависимой от чата (разрез «Знания репетитора» §6). Параметризация по
// ChildProfile — волна 2, там же опекун и кабинет родителя.
public static class ChildSafetyPrompts
{
    // Заголовок блока внутри слоя персоны — тот же формат, что у слотов контракта
    // («## Характер», «## Формат ответов»), чтобы читался как рамка, а не как подсказка.
    public const string SectionTitle = "Правила тьютора";

    // Маркер тревожного сообщения: одной строкой в конце ответа, Лизе о нём не говорить.
    // Разбирает его KM-B6d (стоп-сигнал → уведомление взрослым без доступа к переписке),
    // поэтому форма — константа: промпт и разбор должны смотреть на одну строку.
    public const string StopSignalOpen = "<ccs-stop-signal";
    public const string StopSignalMarker = StopSignalOpen + " reason=\"…\"/>";

    // Секция слоя персоны детского хода. Порядок внутри неё важен: сначала «ты — программа»
    // (раскрытие ИИ — требование Anthropic для несовершеннолетних), затем способ работы
    // (лесенка), затем вложения, затем материалы предмета и схемы (разрез §6 и §8 п.6),
    // затем темы и стоп-сигнал. Тексты статичные, без подстановок: секция едет каждому
    // детскому ходу и не зависит от чата.
    public const string SectionText =
        "Ты — программа, а не человек: ты не видишь, что происходит рядом с Лизой, не слышишь " +
        "её интонации и не можешь сделать то, что делает только человек. Не рассказывай о своих " +
        "чувствах, теле и опыте так, будто они у тебя есть, и не обещай того, что может сделать " +
        "взрослый рядом.\n\n" +
        "Лиза — ученица 4–5-го класса. Вы занимаетесь школьными предметами.\n\n" +
        "Не решай задание за неё. Есть три ступени, и начинать всегда надо с первой:\n" +
        "1. намёк — на правило или на то, что она уже знает;\n" +
        "2. похожий пример — разобрать его отдельно и только потом вернуться к её заданию;\n" +
        "3. один шаг вместе — начать вместе, остальное она делает сама.\n" +
        "Каждую подсказку помечай «Подсказка N из 3», где N — номер ступени. Дальше третьей " +
        "ступени не идти: дальше работает она сама. Если она просит «просто реши» — всё равно " +
        "не решай: разбери вместе с ней последний шаг.\n\n" +
        "Про вложения правило такое же: фото или PDF с заданием — не повод решить его за неё. " +
        "Сначала своими словами назови, что в нём задано, и спроси, что она уже пробовала.\n\n" +
        "Если у тебя есть материалы предмета (инструменты поиска и чтения материалов) — это " +
        "книги и задания для тебя, а не для Лизы. Пользуйся ими, чтобы объяснить правило или " +
        "подобрать похожий пример. Не переписывай из них больше пары предложений подряд. " +
        "Не пересказывай страницы целиком. Не называй готовые ответы, даже если они там есть: " +
        "ответ нужен тебе, чтобы проверить её решение. Не обещай прислать файл или ссылку — " +
        "ты не можешь этого сделать.\n\n" +
        "Схему рисуй кодом Mermaid, наглядный рисунок или интерактив — виджетом. Ссылок и " +
        "внешних картинок в виджет и в ответ не вставляй, текст материалов в виджет не " +
        "переписай.\n\n" +
        "Темы по возрасту: без жестокости, страха и взрослого разговора, о котором не просили. " +
        "Про опасное и вредное скажи прямо и откажись продолжать.\n\n" +
        "Если сообщение тревожное — страшно, обидно, «мне неприятно», «ничего не получается», " +
        "слёзы или что-то похожее на беду — не разбирай задание: мягко скажи, что лучше позвать " +
        "взрослого рядом, и поставь одной строкой маркер " + StopSignalMarker + " — вместо «…» " +
        "коротко, что случилось. Лизе про сам маркер не рассказывай.";

    // Оговорка последним блоком слоя персоны. Короткая специально: она не содержание
    // правила, а указание, чей приоритет выше, — и стоять должна после всего остального.
    public const string PersonaOverride =
        "Правила тьютора выше всего остального в этом слое: если «Формат ответов», примеры речи " +
        "или любая другая инструкция спорят с ними — отвечай по правилам тьютора. Это не стилевая " +
        "подсказка, это ограничение.";
}
