using ClaudeHomeServer.Services.Deploy;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace ClaudeHomeServer.Controllers;

// Выкатка боевого продукта из веб-морды: кнопка просит трей-раннер опубликовать рабочее дерево
// «как есть», а тот гасит продукт, публикует и поднимает обратно (не поднялся — откатывается на
// снимок предыдущей сборки сам).
//
// Зачем это здесь, если выкатку и так умеет запускать скилл из чата: тот способ требует живой
// сессии claude CLI. Кончились лимиты провайдера, сломался CLI — и выкатка недоступна, хотя к
// LLM она никакого отношения не имеет. Кнопка эту зависимость убирает.
//
// Только для админов, и этого мало — фича вдобавок выключена конфигом по умолчанию
// (см. TrayDeployOptions): код уезжает всем, у кого свой инстанс продукта и свой раннер, поэтому
// защитой служит конфигурация, а не отсутствие кода. Скрывать пункт в UI без проверки на
// сервере нельзя — веб-морда торчит наружу.
//
// Режим один — «как есть» (публикуется рабочее дерево со всеми незакоммиченными правками).
// Строгий режим раннера (fetch + ff-only) сюда не вынесен сознательно: он отказывает на грязном
// дереве, а рабочая репа продукта почти всегда грязная — кнопка чаще отвечала бы отказом, чем
// работала.
[ApiController]
[Route("api/admin/deploy")]
[Authorize(Roles = "admin")]
public class TrayDeployController(DeployLauncher deploy, ILogger<TrayDeployController> log) : ControllerBase
{
    /// <summary>
    /// Состояние выкатки. Отвечает 200 ВСЕГДА, даже когда фича выключена: этот эндпоинт зовёт
    /// шапка при каждом монтировании, чтобы решить, рисовать ли пункт меню, и 404 в ответ
    /// шумел бы ошибкой в консоли у каждого админа, у кого фича не включена.
    /// </summary>
    [HttpGet("status")]
    [ResponseCache(NoStore = true, Location = ResponseCacheLocation.None)]
    public IActionResult GetStatus()
    {
        // Запрет кэширования тут не формальность, а лечение конкретного дефекта. Ответ не нёс
        // никаких заголовков кэширования, и браузер по эвристике отдавал модалке один и тот же
        // ответ на серию частых опросов: StartedAt «не менялся», продукт «отвечал» (из кеша!) —
        // и окно честно рапортовало «трей команду не принял» поверх успешной выкатки.
        var availability = deploy.CanLaunch();
        return Ok(new
        {
            enabled = deploy.Enabled,
            canLaunch = availability.CanLaunch,
            reason = availability.Reason,
            status = deploy.ReadStatus(),
        });
    }

    /// <summary>
    /// Запускает выкатку. 202 — команда отправлена трею; дальше следить за ходом фронт должен
    /// сам, потому что продукт (а с ним и это соединение) через мгновение погаснет.
    ///
    /// В ответе — previousStartedAt: время начала ПРОШЛОЙ выкатки из файла статуса. Без него
    /// фронт не отличит свежий итог от старого: раннер перезаписывает файл не сразу (сперва
    /// git-проверки), а при отказе — например, когда удалённая выкатка запрещена в его
    /// конфиге, — не перезаписывает вовсе. Наивный опрос прочитал бы прошлый «ok» и
    /// отрапортовал об успехе, которого не было.
    /// </summary>
    [HttpPost]
    public IActionResult Launch()
    {
        // Выключенная фича — именно 404: «здесь ничего нет» честнее, чем «вам сюда нельзя»,
        // когда дело не в правах.
        if (!deploy.Enabled) return NotFound();

        var availability = deploy.CanLaunch();
        if (!availability.CanLaunch)
        {
            log.LogInformation("Выкатка отклонена для {User}: {Reason}", User.Identity?.Name, availability.Reason);
            return Conflict(new { error = availability.Reason });
        }

        var previousStartedAt = deploy.ReadStatus()?.StartedAt;
        log.LogWarning("Выкатка боевого продукта запрошена пользователем {User}.", User.Identity?.Name);

        // Сигнал уходит строго ПОСЛЕ того, как ответ отправлен. Трей гасит продукт через
        // секунду-другую после события, и ответ, отданный раньше сигнала, до браузера просто
        // не доехал бы — пользователь увидел бы оборванный запрос и не понял, пошла выкатка
        // или нет. Гарантии доставки это всё равно не даёт (процесс убивают), поэтому фронт
        // умеет работать и без этого ответа: он начинает следить по факту нажатия.
        HttpContext.Response.OnCompleted(() =>
        {
            if (!deploy.Signal()) log.LogError("Трей не принял команду выкатки: событие не открылось.");
            return Task.CompletedTask;
        });

        return Accepted(new { previousStartedAt });
    }
}
