    /// <summary>Карточка канала в API плеера.</summary>
    public static string CardUrl(int id) => $"https://player-api.smotrim.ru/api/v1/channel/{id}";

    /// <summary>
    /// Встраиваемый плеер. Формат проверен живьём, играет и на 390 CSS-пикселях.
    ///
    /// Хвост <c>/isPlay/true</c> — автозапуск: без него кадр открывается стоп-кадром и
    /// эфир приходится запускать вторым нажатием уже внутри чужого плеера. Флаги плеер
    /// читает СЕГМЕНТАМИ ПУТИ, а не query-параметрами (там же живут <c>mute</c> и
    /// <c>resumeTime</c>) — «?autoplay=1» он просто не заметит.
    /// </summary>
    public static string EmbedUrl(int id) => $"https://player.smotrim.ru/iframe/channel/id/{id}/isPlay/true";

    /// <summary>Страница канала на сайте — туда уводим каналы без собственного потока.</summary>
    public static string ExternalUrl(int id) => $"https://smotrim.ru/channel/{id}";
