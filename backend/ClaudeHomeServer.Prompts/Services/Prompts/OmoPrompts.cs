{
    // --- Цикл «до готово» (флаг work-loop) ---
    // Тексты — перевод RALPH_LOOP_TEMPLATE / ULW_LOOP_TEMPLATE и continuation-промптов
    // (docs/omo/translations/loops.md); рабочий тег <promise> — протокол детектора, не переводится.

    // Протокол хода: дописывается к каждому сообщению, пока цикл активен
    public static string WorkLoopTurn(string promise) => $"""
        [ЦИКЛ «ДО ГОТОВО»]
        Этот ход выполняется в самоссылающемся цикле разработки, который идёт до верифицированного завершения.

        Как работает цикл:
        1. Ты работаешь над задачей непрерывно.
        2. Когда считаешь, что задача ПОЛНОСТЬЮ завершена, выведи: <promise>{promise}</promise>
        3. Если ты не вывел промис, цикл автоматически подкинет следующий промпт для продолжения.
        4. После промиса система потребует финальную верификацию — не считай «{promise}» финалом, пока верификация не пройдена.

        Правила:
        - Сосредоточься на полном, а не частичном завершении задачи.
        - Не выводи промис завершения, пока задача не сделана по-настоящему.
        - Каждая итерация должна давать осмысленный прогресс к цели.
        - Застрял — сначала пробуй другие подходы; когда без человека дальше нельзя —
          выведи <blocked>краткая причина</blocked>, цикл остановится сам и человек увидит причину.
        - Отслеживай прогресс через todo-инструменты.
        - Делегировал работу исполнителю (tasks_create + tasks_run_executor) и ждёшь его
          доклада — НЕ считай это блокером. Заверши ход, и цикл сам уйдёт в фазу ожидания
          (бейдж «waiting»): доклад исполнителя автоматически вернёт цикл к работе. <blocked>
          оставляй только когда решения человека действительно не хватает (доступ, продуктовое
          решение, физическое препятствие).
        - Ждёшь ответа чужой сессии (chats_send), чужого процесса, человека вне чата или
          иного внешнего события, о котором система знать не может — выведи
          <waiting>чего ждёшь</waiting> и заверши ход. Цикл уйдёт в фазу ожидания и будет
          тикать тебя раз в несколько минут (итерации не тратятся). Ответ на chats_send
          никуда не доставляется — без маркера цикл будет ходить в chats_history по
          кругу и сжигать итерации. Разница с блокером: блокер — нужно решение человека,
          ожидание — нужно время.
        """;

    // Автопродолжение после хода без маркера завершения. Ветка для застревания (2026-08-03,
    // B-п.4): раньше продолжение было безусловным, а у скилла есть законные условия остановки
    // (например, одна и та же ошибка трижды подряд) — модель либо жгла бюджет до лимита, либо
    // получала стимул соврать промис завершения, лишь бы вырваться. Явно легализуем честную
    // остановку: цикл всё равно доведёт до предела итераций (с явным сообщением — см. B-п.3),
    // но без давления изображать готовность.
    public static string WorkLoopContinuation(string promise, int iteration, int max) => $"""
        [СИСТЕМНАЯ ДИРЕКТИВА — ЦИКЛ «ДО ГОТОВО» {iteration}/{max}]
        Продолжай. Когда закончишь, выведи <promise>{promise}</promise>.

        Если работа встала на препятствии (одна и та же ошибка повторяется третий раз подряд,
        или дальше двигаться без решения человека нельзя) — не изображай готовность и не выводи
        промис. Выведи <blocked>краткая причина</blocked> — цикл остановится сам, и человек
        увидит причину. Это законное завершение хода, а не провал.

        Делегировал работу исполнителю и ждёшь его доклада — НЕ вставай в <blocked>. Заверши
        ход, цикл сам уйдёт в фазу ожидания (бейдж «waiting»), и приход доклада вернёт его
        к работе без потери итераций.

        Ждёшь ответа на chats_send, чужого процесса, человека вне чата или иного внешнего
        события, о котором система знать не может — выведи <waiting>чего ждёшь</waiting>
        и заверши ход. Цикл перейдёт в фазу ожидания и будет тикать тебя раз в несколько
        минут; итерации при этом не тратятся. Маркер НЕ обязателен для ожидания доклада
        делегированной задачи — там цикл понимает сам по факту задачи. Разница с блокером:
        блокер — нужно решение человека, ожидание — нужно время.
        """;

    // Финальный верификационный ход после маркера. В оригинале верифицирует субагент-Оракул;
    // у нас верификация — тем же агентом со свидетельствами (или ревьюером-субагентом, если доступен).
    public const string WorkLoopVerification = """
        [СИСТЕМНАЯ ДИРЕКТИВА — ВЕРИФИКАЦИЯ ЦИКЛА]

        Ты вывел промис завершения. Это ещё НЕ завершает цикл.

        ТРЕБУЕТСЯ СЕЙЧАС:
        - Проверь скептически и критически, действительно ли исходная задача завершена: ищи причины, по которым она может быть всё ещё не завершена или сделана неверно.
        - Прогони фактические проверки (сборка, тесты, реальный результат) и приведи свидетельства.
        - Если доступен субагент-ревьюер — делегируй ему проверку синхронно (не в фоне) и включи исходную задачу в запрос.
        - Нашёл проблемы — почини их сейчас и перепроверь.
        - В конце подведи честный итог: что проверено, какими свидетельствами подтверждено завершение, что осталось (если осталось).
        """;

    // Тик ожидания по маркеру `<waiting>`: координатор в фазе ожидания, итерации не тронуты,
    // но прошло уже N тиков из M (один тик — раз в Loop:WaitingTickSeconds секунд). Цель —
    // разбудить координатора спустя время, чтобы он посмотрел, пришёл ли ответ, и либо
    // продолжил работу, либо снова вывел `<waiting>` с той же причиной. Молчание на тике —
    // тупик, и координатор обязан что-то с этим сделать (проверить инструмент, обновить
    // причину, переключиться на `<blocked>` если событие вправду не пришло).
    public static string WorkLoopWaitingTick(string? reason, int ticks, int max, int tickSeconds) => $"""
        [СИСТЕМНАЯ ДИРЕКТИВА — ТИК ОЖИДАНИЯ ЦИКЛА {ticks}/{max}]
        Ты в фазе ожидания по своему маркеру <waiting>{(reason is null ? "" : reason)}</waiting>
        уже {ticks * tickSeconds / 60} минут (тик раз в {tickSeconds} секунд).

        Проверь, не пришёл ли результат того, чего ты ждёшь. Если пришёл — продолжай работу:
        новый `<waiting>` НЕ выводи, и цикл сам вернётся в фазу working. Если не пришёл и
        ждать дальше осмысленно — снова выведи <waiting>{(reason is null ? "прежняя причина" : reason)}</waiting>
        и заверши ход. Если событие вправду не придёт и продолжать нельзя — выведи
        <blocked>почему ожидание бессмысленно</blocked>, цикл остановится и человек решит.
        """;

    // --- Категории делегирования (подсказка оркестратору/исполнителю задач) ---
    // const DelegationCategories — в OmoPrompts.Categories.cs (генерируется из
    // docs/omo/translations/categories.md): 8 категорий из delegate-task.
}
