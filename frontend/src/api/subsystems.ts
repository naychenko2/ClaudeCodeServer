// API-методы экрана «Подсистемы» (Этап 5, волна 3): чтение списка и
// переключение тумблера по ключу. Эндпоинты — `/api/admin/subsystems` и
// `/api/admin/subsystems/{key}` (контракт соседней волны, бэкенд-контроллер
// админки подсистем). Отдельный модуль — рядом с `api/chats.ts` и
// будущими продуктовыми API: каждое направление держим в своей папке,
// чтобы их состав был виден за минуту.
//
// Контракт записи — по макету `docs/mockups/subsystems-admin.md` (шесть полей).
// `enabledConfigured` отражает запись в конфиге инстанса, `enabledRuntime` —
// что реально поднято в текущем процессе. Расхождение двух значений
// означает «изменение сохранено, но ещё не применено — нужен перезапуск»;
// это же расхождение рисует экран как warning-баннер.

import { request } from '../lib/offline';

// Запись подсистемы в ответе `GET /api/admin/subsystems`.
// Шесть полей по макету: ключ якоря строки, имя, описание, два состояния
// и признак рубильника. Без рубильника (canToggle: false) — часть ядра,
// тумблер физически не рисуется.
export interface Subsystem {
  key: string;
  title: string;
  description: string;
  enabledConfigured: boolean;
  enabledRuntime: boolean;
  canToggle: boolean;
}

// Ответ GET — единый массив подсистем под ключом `subsystems`.
// Контракт соседней волны; форма кладётся рядом с другими админскими
// списками (feature-flags, image-generation) для предсказуемости.
export interface SubsystemsListResponse {
  subsystems: Subsystem[];
}

export const subsystemsApi = {
  // Список подсистем инстанса с их настройками и фактическим состоянием.
  // GET без оптимистичной логики: страница открылась — пользователь увидел
  // ровно то, что отдаёт сервер, без локальных догадок.
  get: () => request<SubsystemsListResponse>('/admin/subsystems'),

  // Переключить тумблер по ключу. Сервер сохраняет новое значение в
  // `enabledConfigured`; в рантайме оно применится только после перезапуска
  // (отдельный баннер на экране говорит об этом пользователю). На успехе
  // сервер возвращает обновлённую запись — её мы и подставляем в локальный
  // список, чтобы строка перерисовалась по ответу (макет: «оптимистичного
  // применения нет — перерисовываем строку по ответу сервера»).
  set: (key: string, enabled: boolean) =>
    request<Subsystem>(`/admin/subsystems/${encodeURIComponent(key)}`, {
      method: 'PUT',
      body: JSON.stringify({ enabled }),
    }),
} as const;
