namespace ClaudeHomeServer.Services;

// Сведения о базе знаний рабочего дерева, нужные ХОДУ: идентификатор Dify-датасета и
// карта тегов документов. Оба поля читаются в одном месте — при сборке хода: по датасету
// объявляется MCP-сервер `dify`, по обоим — автодополнение системного промпта проекта
// (SystemPromptComposer.GetSystemPromptParts: блок про базу знаний и инструкция по тегам).
public sealed record WorkspaceDatasetInfo(
    string? DatasetId,
    Dictionary<string, List<string>>? DocumentTags);

// Узкий шов WorkspaceKnowledgeStore для выноса Llm (Этап 5). Из всего стора знаний
// рабочих деревьев ходу нужно ОДНО чтение по корню дерева, и делать его надо на КАЖДЫЙ
// ход: датасет мог появиться уже после создания сессии, поэтому кэшировать нельзя.
//
// Полный `WorkspaceKnowledgeStore` умеет ещё запись (Set/Remove), снимок ВСЕХ записей для
// реконсайлера error-документов и нормализацию путей. Вертикали Llm не нужно ничего из
// этого, и шов сознательно не отдаёт ни мутаций, ни перечисления: чужие рабочие деревья
// ход видеть не должен, а нормализация путей и так живёт в спине (`PathNormalizer`).
public interface IWorkspaceDatasetLookup
{
    // Знания рабочего дерева по его корню; null — знания для этого дерева не заводились
    // (штатный случай: MCP-сервер dify тогда не объявляется, блока про базу знаний в
    // промпте нет).
    WorkspaceDatasetInfo? ForRoot(string rootPath);
}
