// Единый каталог действий чата — общий для карточки в списке и шапки открытого чата.
// Оба места показывают ОДИН набор: что доступно, решают колбэки/контекст (закрепление
// живёт только у чатов вне проекта, досье — только у проектных, стена — у воркспейса),
// а что стоит кнопкой снаружи, а что живёт в меню — выбор пользователя (глазик).
//
// Здесь только метаданные: ключ, подпись и дефолтная видимость. Исполнение действия
// у каждого места своё (в карточке переименование правит имя на месте, в шапке —
// диалогом), и склеивать эти реализации в один рантайм смысла нет.

export type ChatActionKey =
  | 'rename' | 'pin' | 'tags' | 'wall' | 'notify' | 'dossier' | 'expiry' | 'delete';

// Порядок — канонический: в каком бы месте действие ни рисовалось, соседи те же
export const CHAT_ACTION_ORDER: ChatActionKey[] = [
  'rename', 'pin', 'tags', 'wall', 'notify', 'dossier', 'expiry', 'delete',
];

