// Дательный падеж имени собеседника — для подписей вида «Написать Вере…».
// Склоняем только однозначные случаи по окончанию; неоднозначное (мягкий знак: Игорь →
// Игорю, но Любовь → Любови), составное или смешанное имя возвращает null — вызывающий
// тогда пишет фразу без имени: лучше без имени, чем с ошибкой.
// Имя без кириллицы (Claude, DeepSeek, GLM 5) не склоняется и возвращается как есть.

const CYR = /[а-яё]/i;
const CONSONANT_END = /[бвгджзклмнпрстфхцчшщ]$/i;

export function dativeName(name: string): string | null {
  const n = name.trim();
  if (!n) return null;
  if (!CYR.test(n)) return n;
  // Только одно слово из кириллицы с заглавной: «ГР», «Вера Павловна», «Bot-Вера» — мимо
  if (!/^[А-ЯЁ][а-яё]+$/.test(n)) return null;
  if (/ия$/.test(n)) return n.slice(0, -1) + 'и';   // Мария → Марии, София → Софии
  if (/[ая]$/.test(n)) return n.slice(0, -1) + 'е'; // Вера → Вере, Илья → Илье
  if (/й$/.test(n)) return n.slice(0, -1) + 'ю';    // Дмитрий → Дмитрию, Сергей → Сергею
  if (CONSONANT_END.test(n)) return n + 'у';        // Олег → Олегу, Максим → Максиму
  return null;
}
