// === Ширины центрированного контента ===
// Две роли, и путать их нельзя.
//
// CHAT_MAX_W — КОЛОНКА ЧТЕНИЯ: лента сообщений, композер, текст заметки, лента
// «Что нового». Здесь ширину диктует длина строки: шире — глазу труднее возвращаться
// к началу следующей строки. Расширять под сетки нельзя.
//
// CONTENT_MAX_W — СЕТКА РАЗДЕЛА: дашборд главной, календарь, уведомления, аналитика,
// хаб персон. Здесь ширину диктует раскладка карточек, а не текст.
//
// Раньше вместо второй константы жил разнобой из литералов (1080 / 1180 / 1220 / 1244),
// и разделы выглядели как разные продукты. Новое центрированное «полотно» раздела —
// сюда, не литералом.
//
// ВАЖНО: обе константы задают ВИДИМУЮ ширину контента, а не внешнюю ширину коробки.
// box-sizing у всего проекта — border-box (index.css), поэтому боковой padding на том
// же элементе съедает ширину: `maxWidth: CONTENT_MAX_W, padding: '0 32px'` даст видимых
// 1116, а не 1180, и раздел снова разъедется с соседями. Боковые отступы вешать на
// РОДИТЕЛЯ (скролл-контейнер), центрируемому элементу оставлять только вертикальные.
// HOME_MAX_W — ДАШБОРД главной. Отдельная величина между двумя первыми, и это
// осознанный выбор, а не забытый литерал: виджеты стоят в две колонки, поэтому
// колонка чтения для них тесна (по ~465px на колонку), а сетка раздела —
// наоборот, растягивает карточки в полосы. 1028 даёт колонки примерно по 500px.
export const CHAT_MAX_W = 950
export const HOME_MAX_W = 1028
export const CONTENT_MAX_W = 1180

// CHAT_GUTTER_L — боковое поле СЛЕВА от колонки сообщений. Геометрию области
// прокрутки по нему считает chatGutter.ts (marginRight гасит перекос «поле слева
// против полосы прокрутки справа», поэтому колонка сообщений и композер остаются
// по центру окна при любом размере), здесь величина живёт как размерный токен —
// от неё же считается CHAT_COLUMN_W ниже.
//
// Раньше здесь было 52: индикатор ожидания («домик» с кольцами «Эхо») выносился
// ЗА левый край ленты отрицательным отступом, и под него держали целый жёлоб. На
// стене (узкая колонка, компенсации нет) это читалось как «текст уехал вправо», а
// сам домик лез на рамку колонки. Теперь индикатор стоит В ПОТОКЕ, по левому краю
// сообщений, и поле нужно только под размах колец: они выступают за аватар на ~12px
// (scale 1.85 от 28), иначе их режет клип области прокрутки (overflow-x: hidden).
// 16 — этот минимум с небольшим запасом: больше поле не нужно ничему, а лишний
// воздух по бокам отъедает текст на узком окне и в колонке стены.
//
// ТА ЖЕ величина идёт в боковые поля композера и кнопки «вниз» (см. ChatPanel):
// на узком окне колонка упирается в края, и разные значения развели бы левый край
// сообщений с левым краем поля ввода.
export const CHAT_GUTTER_L = 16

// CHAT_COLUMN_W — сколько лента чата занимает ПО ГОРИЗОНТАЛИ целиком, вместе с
// обвязкой: боковое поле слева + колонка чтения + место под полосу прокрутки справа +
// внешний отступ, который гасит перекос «поле против полосы». Ширина полосы
// сокращается (см. gutterBox), поэтому итог не зависит от системы: CHAT_MAX_W + 2×поле.
//
// Зачем отдельно от CHAT_MAX_W: это НЕ ширина текста, а запрос ленты к раскладке.
// Тому, кто раздаёт место (useCenterOffset — он решает, сколько свободного запаса
// колонки можно съесть компенсацией перекоса зон), нужна именно она. Дашь ему 950 —
// он посчитает последние 80px свободными и отдаст их под padding, и лента начнёт
// сжиматься раньше времени, вдвое быстрее движения панели.
export const CHAT_COLUMN_W = CHAT_MAX_W + CHAT_GUTTER_L * 2

// SPLASH_W — сколько занимает по горизонтали заставка пустого центра (иконка,
// заголовок «С чего начнём?», подпись и кнопка): карточка 400 + её паддинги 24×2.
