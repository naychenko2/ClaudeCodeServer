namespace ClaudeHomeServer.Services.Prompts;

// Сценарное правило выбора инструмента навигации по коду (ADR-011 шаг 3): три уровня —
// codegraph (типы и связность), LSP (символ и позиция), Grep (текст) — не взаимозаменяемы.
// Замер ADR-011 показал, что модель зовёт то, про что написано в промпте: у codegraph
// сценарное правило было (95 вызовов за 14 дней), у LSP — ни слова (8 вызовов при
// исправном C#-стеке). Единая точка истины формулировок: и глобальный блок хода, и тексты
// пресетов секции «Навигация по коду» (SpecialtyPromptPresets, id codeGraph) берут
// строки отсюда — дублировать формулировки в двух файлах нельзя.
//
// Двухуровневый разрез, как у графа кода:
//  - SectionText — глобальная секция "code-navigation" в КАЖДОМ ходе проектного чата.
//    Страхует покрытие: секция специальности возвращает null без персоны/специальности,
//    в групповом чате и при выключенном флаге specialty-prompt-sections. Поэтому короткая.
//  - Пресетные кирпичики (Preset*) — развёрнутые сценарии ролей в SpecialtyPromptPresets.
//
// Вставляется секцией "code-navigation" рядом со slice графа, но НЕ зависит от его
// построения: slice — данные (хабы, словарь), правило — контракт «когда кого звать»,
// и должен доехать до каждого хода проектного чата, включая свежий проект без графа.
// Сценарные правила codegraph раньше жили в хвосте slice (RenderSlice) и переехали сюда,
// чтобы ролевое разделение фиксировалось одним блоком и не дублировалось в промпте.
//
// Текст промпта, не инструмент: состав tools/list и сигнатуру запуска CLI не меняет
// (инвариант McpToolsetStabilityTests). Выкатывается вместе с LSP-1 (починка TS-LSP):
// правило без рабочего TS-сервера научило бы модель звать заведомо сломанный инструмент.
public static class CodeNavigationPrompts
{
    // Глобальная секция системного промпта хода (ключ "code-navigation"). Формулировка —
    // момент выбора, а не перечень возможностей: сухой перечень уже доказал, что не работает.
    // Едет в каждый ход — держать короткой, развёрнутые сценарии живут в секции специальности.
    public const string SectionText =
        "## Навигация по коду: три уровня, не взаимозаменяемы\n" +
        "• codegraph — типы и связность: «с чего начать разбор» — codegraph_hubs; " +
        "«кто висит на типе / что сломается» — codegraph_neighbors; «где объявлен тип» — codegraph_find.\n" +
        "• LSP — символ и позиция: «где определён именно этот символ» — goToDefinition; " +
        "«все использования / кто вызывает метод» — findReferences. Семантическая точность: Grep даёт однофамильцев.\n" +
        "• Grep — текст, строки, конфиги и всё, что не символ.\n" +
        "Собрался переименовать символ — сначала LSP findReferences, а не Grep.";

    // Буллет LSP-уровня для пресетов секции «Навигация по коду»: вклеивается в список
    // «Когда звать» каждой роли. Формулировка одна на все роли — роль добавляет лишь
    // языковую привязку (.cs / .tsx) в собственном тексте.
    public const string PresetLspLine =
        "• «где определён именно этот символ / все его использования» — LSP goToDefinition / " +
        "findReferences: точность семантическая, Grep даёт однофамильцев и пропускает косвенные.";

    // Момент выбора для пресетов: главный сценарий LSP — переименование, задевающее
    // всех пользователей символа. Один и тот же у всех ролей.
    public const string PresetRenameMoment =
        "Переименование символа — сначала LSP findReferences, а не Grep.";
}
