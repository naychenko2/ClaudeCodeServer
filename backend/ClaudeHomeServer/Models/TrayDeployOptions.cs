namespace ClaudeHomeServer.Models;

// Выкатка на бой из веб-морды: пункт меню, который просит трей-раннер опубликовать продукт.
//
// Зачем эта настройка вообще существует. До сих пор выкатку запускал только личный скилл из
// чата — то есть механика жила ВНЕ репозитория, и на чужой машине не заводилась в принципе.
// Пункт меню — это код в общей репе, и он уезжает всем, у кого свой инстанс продукта и свой
// раннер. Поэтому защитой служит не отсутствие кода, а конфигурация: Enabled по умолчанию
// false, а реальные значения живут в машинном appsettings.Local.json, который вне git.
//
// В дев-инстансе (Rider, Development) включать НЕ надо: appsettings.Local.json читается и там,
// так что кнопка в отладочном запуске выкатывала бы боевой продукт.
public class TrayDeployOptions
{
    public const string Section = "TrayDeploy";

    // Главный рубильник фичи. Выключено — пункта меню нет, а POST отвечает 404.
    public bool Enabled { get; set; }

    // Именованное событие, которым трей-раннер принимает команду «опубликовать рабочее дерево».
    // Мы ставим его сами (см. DeployLauncher), а не запускаем ClaudeServerTray.exe с ключом:
    // при мёртвом трее такой запуск поднял бы ВТОРОЙ трей, дочерний нашему процессу, и тот
    // погасил бы боевой продукт как осиротевший — то есть собственного родителя.
    //
    // Значение — межрепный контракт с раннером (Program.DeployAsIsEventName). Переименуют его
    // там — кнопка начнёт молча отвечать «трей не отвечает», а искать причину будут здесь, где
    // всё исправно. Потому имя и вынесено в конфиг, а не зашито константой.
    public string EventName { get; set; } = "ClaudeServerTray_DeployAsIs_9E1C";

    // Где раннер оставляет итог выкатки. Пусто — ищем рядом с собой: на бою продукт и файл
    // лежат в одной папке. Настройка нужна потому, что у раннера путь считается от его
    // ProductWorkingDir, а тот задаётся независимо от пути к exe продукта.
    public string StatusPath { get; set; } = "";

    // Через сколько минут висящий в файле статус «running» считать протухшим, а не текущей
    // выкаткой. Своя настройка, а не оглядка на DeployTimeoutMin раннера: его конфиг нам не
    // виден, а худший случай (долгая сборка + health-проба + откат по robocopy) выходит за
    // полчаса. Протухший running означает «трей умер посреди работы» и запуск не блокирует.
    public int StaleRunningMin { get; set; } = 60;
}
