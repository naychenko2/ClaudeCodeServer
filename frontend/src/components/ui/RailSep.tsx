import { C } from '../../lib/design';

// Разделитель в вертикальной рельсе — общий для рельсы панелей и дока проектов.
// Два типа, и они означают разное:
//
//   group — граница между НАБОРАМИ кнопок: служебные (режим зоны, «свернуть все»)
//           против кнопок панелей. Сплошная черта, полный воздух.
//   inner — граница ПОДГРУППЫ внутри одного набора: инструменты проекта против
//           панелей текущей сессии, закреплённые проекты против недавних. Пунктир
//           и меньший воздух — столбик читается как один ряд с перегородкой, а не
//           как две отдельные группы кнопок.
//
// Пунктир рисуется границей, а не заливкой: у элемента с нулевой высотой штрихи
// задаёт сама рамка. Скругления быть не должно — на схлопнутом content браузер
// рисует его дугой, и штриховка вырождается в сплошную линию.
export function RailSep({ variant = 'group', margin, mark }: {
  variant?: 'group' | 'inner';
  // Переопределение вертикального ритма: у служебных границ рельсы отступы
  // несимметричны, чтобы центры кнопок остались на своих линиях.
  margin?: string;
  // Пометить разделитель для перетаскивания: по нему док проектов понимает, в
  // какую группу метит курсор (см. computeInsert в ProjectRail).
  mark?: boolean;
}) {
  const inner = variant === 'inner';
  return (
    <div
      {...(mark ? { 'data-sep': '' } : null)}
      style={{
        width: 22, flexShrink: 0,
        margin: margin ?? (inner ? '-1px 0' : '2px 0'),
        ...(inner
          ? { height: 0, borderTop: `1px dashed ${C.border}` }
          : { height: 1, background: C.border }),
      }}
    />
  );
}
