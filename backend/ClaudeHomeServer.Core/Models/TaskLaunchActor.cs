namespace ClaudeHomeServer.Models;

// Актор хода при АВТОзапуске исполнителя (F-9): автозапуск не имеет живого инициатора, поэтому
// ход наследует создателя задачи (TaskItem.CreatedByUserId), а не «неизвестного». Создатель —
// участник-редактор общего проекта ⇒ ход идёт с его рангом и закрытые ему инструменты
// исполнителю тоже закрыты.
//
//  • создатель задан и это не владелец записи — он и есть актор;
//  • создатель — владелец, не задан (старая запись, фон, система) или пуст — актором называется
//    владелец записи (task.OwnerId): «старые задачи считаются созданными владельцем» теперь
//    записано именем буквально. Раньше здесь был null — он значил «права владельца» в
//    ActorRightGate; после О2 финального ревью «Общих проектов» (892deb00) null значит «никаких
//    прав» (в общем проекте), и безымянность отняла бы исполнителю его собственную задачу.
//    Пустой OwnerId (записи нет) остаётся null — fail-closed, как у незнакомой записи.
//  • личный проект: создатель там всегда владелец, поведение прежнее (там и null был бы
//    разрешён, но имя честнее и результат тот же).
public static class TaskLaunchActor
{
    public static string? For(TaskItem task) =>
        string.IsNullOrWhiteSpace(task.CreatedByUserId) || task.CreatedByUserId == task.OwnerId
            ? (string.IsNullOrWhiteSpace(task.OwnerId) ? null : task.OwnerId)
            : task.CreatedByUserId;
}
