using System.Text;
using System.Text.RegularExpressions;

namespace ClaudeHomeServer.Services.Notes.Wiki;

// Числа утверждения и их подтверждение цитатами (ADR-039, решение 2): каждое число
// в claim обязано встречаться в одной из его цитат, иначе операция идёт во
// «Входящие» с причиной «число не подтверждено цитатой». Проверка — по целым
// числам после нормализации: «12» не подтверждается цитатой с «123», а «−12» —
// цитатой без знака. Числами утверждения не считаются: метки сносок, токены,
// слитые с буквами и продолжающиеся через знак («686d58247» — id коммита, а не
// «686» и «58247»; «S2-2», «U+2212», «этап-2» — знак сразу после идентификатора
// или слова-метки относится к идентификатору), и целое число
// сразу после слова-метки («этап 2», «№ 5» — индекс раздела, не количество;
// десятичное после метки — предмет утверждения, «Версия 2.28» остаётся числом);
// метки и идентификаторы вырезаются из claim и из цитат до разбора. Производные
// числа (среднее, темп) и составные индексы («3.1.2») — следующая волна; маркеры
// перечисления «1) 2) 3)» — не числа (дефект aa549944), вырезаются так же, как
// метки (пробелом), и из claim, и из цитат. Из claim дополнительно вырезается
// текст уцелевших [[ссылок]] (доработка Q1-S4, вердикт 3007451c): число в заголовке
// ссылки — не число утверждения, его автор — страница цели; текст снятой ссылки
// к этому времени уже обычный текст утверждения, его числа считаются. Правило
// здесь одно: валидатор и применение считают числа этим же методом.
internal static class WikiClaimNumbers
{
    // Метки сносок [^1] и [^sN]: их цифры — не числа утверждения, вырезаются до
    // разбора и из claim, и из цитат: иначе номер сноски считался бы неподтверждённым
    // числом, а «[^1]» в цитате ложно подтверждал бы число claim («в 1 случае»).
    // Вырезание — пробелом, как у меток и маркеров (хвост bdb97c26, п.13):
    // «12[^1]34» даёт 12 и 34, а не склеенные в «1234».
    private static readonly Regex FootnoteMarker = new(@"\[\^s?\d+\]", RegexOptions.Compiled);

    // Основа слов-меток перед числом (дефект f68d3d82): «этап 2», «шаг 3»,
    // «версии 5», «№ 5», «#10» — индекс раздела или последовательности, а не
    // количество. Список — эта единственная константа, паттерн собран из неё;
    // основа усечена до неизменяемой части слова («версия» → «верси», «волна» →
    // «волн»), падежные формы («этапа», «версии», «волне») дописывает суффикс
    // [а-яё]*. Метка обязана стоять на начале слова: «подэтап 5» числом-меткой
    // не считается.
    private static readonly string[] LabelWords =
        ["этап", "шаг", "пункт", "верси", "вариант", "волн", "раздел"];

    // Метка отсекает только целое число-индекс: за числом не должно стоять ни
    // десятичного разделителя, ни буквы (составные индексы «3.1.2» — следующая
    // волна). «Версия 2.28» остаётся числом утверждения: десятичное число после
    // метки — предмет утверждения (версия, как метрика), а не индекс раздела.
    private static readonly Regex LabelNumber = new(
        @"(?<!\p{L})(?:№|#|" + string.Join("|", LabelWords) + @")[а-яё]*[\s№]*[0-9]+(?![0-9.,\p{L}])",
        RegexOptions.Compiled | RegexOptions.IgnoreCase);

    // Маркер перечисления (дефект aa549944): токен «N)» на начале строки или после
    // пробела, «:», «;» — «1) рост 2) спад». После скобки («(5)») или слова
    // («S2)») — не маркер: это число или часть идентификатора. Вырезается только
    // маркер из ряда «1) 2) …» подряд от 1 длиной ≥ 2: одиночное «5)» и ряд, не
    // начинающийся с 1 («2) а 3) б»), — числа, остаются. Правило консервативное:
    // лишнее число уходит к человеку в «Входящие», на страницу ничего не
    // публикуется неподтверждённым.
    private static readonly Regex EnumMarker = new(
        @"(?<=^|[\s:;])([0-9]+)\)",
        RegexOptions.Compiled);

    // Внутренние знаки идентификатора: дефис, плюс, минус U+2212 (дефис — последним
    // в классе, чтобы читался литералом). Тире (U+2013, U+2014) среди них нет:
    // «0,3–0,7» остаётся двумя числами.
    private const string IdInnerSigns = "−+-";

    // Токены из букв и цифр, в том числе через знак между частями («686d58247»,
    // «a1b2», «S2-2», «U+2212», «этап-2»): число, слитое с буквами (латиница или
    // кириллица) с любой стороны, — часть идентификатора (id коммита, слаг), а не
    // число утверждения; токен вырезается целиком, поэтому его половинки («686»,
    // «58247») не становятся отдельными числами. Та же граница закрывает третий
    // пункт дефекта f68d3d82: знак сразу после идентификатора или после слова-метки
    // относится к идентификатору и не читается знаком числа — «S2-2», «s2a-2» и
    // «этап-2» не дают числа «-2», а «U+2212» (плюс не буквенно-цифровой) — всего
    // идентификатор, а не число 2212. Чисто цифровой или чисто буквенный токен —
    // не идентификатор: «16384» остаётся числом, «abc» — не число; знак между двумя
    // числами без букв — не часть идентификатора: «123-456», «0.3-0.7» и «12 -34»
    // разбираются как раньше.
    private static readonly Regex AlnumToken = new(
        @"(?<![\p{L}\p{N}])(?=[\p{L}\p{N}" + IdInnerSigns + @"]*\p{L})(?=[\p{L}\p{N}" + IdInnerSigns + @"]*\p{N})[\p{L}\p{N}]+(?:[" + IdInnerSigns + @"][\p{L}\p{N}]+)+(?![\p{L}\p{N}])|(?<![\p{L}\p{N}])(?=[\p{L}\p{N}]*\p{L})(?=[\p{L}\p{N}]*\p{N})[\p{L}\p{N}]+(?![\p{L}\p{N}])",
        RegexOptions.Compiled);

    // Разделители тысяч: обычный пробел, U+00A0, U+202F. Коды явные — в исходнике
    // нет невидимых литералов, класс регулярки и проверка собраны из этих констант.
    private const char SpaceNbsp = (char)0x00A0;
    private const char SpaceNarrow = (char)0x202F;

    // Знак числа: минус ASCII и «−» U+2212; к сравнению сводится к ASCII. Тире
    // (U+2013, U+2014) знаком не считается: «0,3–0,7» остаётся двумя числами.
    private const char MinusAscii = '-';
    private const char MinusUnicode = (char)0x2212;

    // Класс разделителей тысяч — в хвосте числа, собран из констант выше:
    // невидимых литералов в исходнике нет. Таб сюда не входит: «1\t000» — два
    // числа, а не 1000 (хвост bdb97c26, п.10); таб стоит только в охране знака.
    private static readonly string ThousandsSpaceClass = "[ " + SpaceNbsp + SpaceNarrow + "]";

    // Охрана знака: разделители тысяч плюс таб — «12\t-34» даёт то же, что
    // «12 -34»: два числа (хвост bdb97c26, п.10). Отдельный класс, чтобы таб
    // не попал в хвост числа.
    private static readonly string SignGuardSpaceClass = "[ " + SpaceNbsp + SpaceNarrow + @"\t]";

    // Хвост числа: цифры; далее — только разделители тысяч строго перед группой ровно
    // из 3 цифр (группа из 4 цифр после пробела — уже не разделитель тысяч,
    // а другое число: «12 3456» даёт «12» и «3456»); далее — не более одного
    // десятичного разделителя «.» или «,». «0,3–0,7» — тире не входит в число:
    // два отдельных числа. «17.08» — одно число, даты тоже проверяются.
    private static readonly string NumberTail =
        "[0-9]+(?:" + ThousandsSpaceClass + "[0-9]{3}(?![0-9]))*(?:[.,][0-9]+)?";

    // Число — без знака (первая ветка) или со знаком минуса (вторая). Знак входит
    // в токен и не стоит после цифры или десятичного разделителя: «123-456» и
    // «0.3-0.7» — по-прежнему два числа, а не одно отрицательное. Не является знаком
    // и после числа с любым пробелом перед ним: «12 -34» — список из двух чисел,
    // «12» и «34» (дельта-ревью S2-2, п.8): дефис сразу после числа относится к
    // предыдущему числу, знак здесь был бы ложным чтением. Одиночное «−12 °C»
    // (без числа перед знаком) остаётся отрицательным. Таб в охране знака — то же,
    // что пробел: «12\t-34» — два числа (хвост bdb97c26, п.10); в разделитель
    // тысяч таб не входит — там остаётся ThousandsSpaceClass.
    private static readonly Regex Number = new(
        NumberTail + "|(?<![0-9.])(?<![0-9]" + SignGuardSpaceClass + "+)[" + MinusAscii + MinusUnicode + "]" + NumberTail,
        RegexOptions.Compiled);

    // Ссылка в claim — та же [[…]], что читает гейт со страницы (тот же образец, что
    // ClaimLinkRx валидатора: «]]» внутри цели не встречается). Её текст — не часть
    // утверждения: число в заголовке ссылки не число утверждения, его автор — страница
    // цели. Снятой ссылки здесь уже нет: её текст к этому времени обычный текст
    // утверждения, его числа считаются.
    private static readonly Regex ClaimLinkRx = new(@"\[\[([^]\r\n]+)\]\]", RegexOptions.Compiled);

    /// <summary>Числа из claim, которых нет ни в одной цитате (пусто — всё
    /// подтверждено). Порядок — по первому вхождению в claim, без дублей; значения
    /// — нормализованные (пробелы внутри числа убраны, запятая свёрнута к точке,
    /// знак-min U+2212 свёрнут к ASCII). Перед разбором из claim и из цитат
    /// вырезаны метки сносок, идентификаторы из букв и цифр, числа после слов-меток
    /// и маркеры перечисления из ряда «1) 2) …»; из claim — ещё текст уцелевших
    /// [[ссылок]] (число в заголовке ссылки не число утверждения; текст снятой
    /// ссылки уже обычный текст, его числа считаются).
    /// Null claim — ничего проверять нечем: пустой результат.
    /// Null цитат и пустой список — одно и то же: утверждения без цитат подтвердить
    /// нечем, все его числа неподтверждены (дельта-ревью S2-2, п.9).</summary>
    internal static IReadOnlyList<string> Unconfirmed(string? claim, IReadOnlyList<string>? quotes)
    {
        if (claim is null)
            return [];

        var confirmed = new HashSet<string>();
        if (quotes is not null)
            foreach (var quote in quotes)
                foreach (var n in Numbers(quote))
                    confirmed.Add(n);

        var result = new List<string>();
        var seen = new HashSet<string>();
        // Числа считаются по claim без текста уцелевых ссылок — одно правило на
        // валидатор и применение (доработка Q1-S4, вердикт 3007451c): второй копии
        // правила в проекте нет.
        foreach (var n in Numbers(WithoutLinkSpans(claim)))
            if (!confirmed.Contains(n) && seen.Add(n))
                result.Add(n);
        return result;
    }

    // Claim для проверки чисел: текст уцелевших ссылок вырезается пробелом, чтобы
    // числа не склеивались с заголовком («12[[x]]34» — это 12 и 34, не 1234; тот же
    // приём, что у меток выше).
    private static string WithoutLinkSpans(string claim) => ClaimLinkRx.Replace(claim, " ");

    // Максимальные вхождения чисел по тексту, нормализованные: сравнение целыми
    // токенами, поэтому «123» не порождает «12» и «12» не подтверждается «123».
    // До разбора из текста вырезается то, что числами не является: метки сносок,
    // идентификаторы из букв и цифр, числа сразу после слов-меток и маркеры
    // перечисления из ряда «1) 2) …». Вырезается пробелом, а не пустой строкой:
    // «12 этап 34» не должно склеиваться в «1234».
    private static IEnumerable<string> Numbers(string text)
    {
        text = StripEnumMarkers(AlnumToken.Replace(LabelNumber.Replace(FootnoteMarker.Replace(text, " "), " "), " "));
        foreach (Match m in Number.Matches(text))
            yield return Normalize(m.Value);
    }

    // Ряд перечисления (дефект aa549944): обход кандидатов «N)» по тексту слева
    // направо; ряд — непрерывный по кандидатам рост 1, 2, 3, … от 1 длиной ≥ 2
    // («1) рост 2) спад 3) рост»); ряд обрывается первым кандидатом не по месту
    // («5)» после 1)–2), «3)» вместо 2)): оборванный короче 2 — не перечисление
    // вовсе, «2) а 3) б» — не ряд: не начинается с 1). Лишнее число консервативно
    // остаётся числом утверждения: оно уйдёт к человеку в «Входящие», на страницу
    // ничего не публикуется. Вырезание — пробелом, как у меток: «103) 1) a 2) b»
    // не должно склеиваться в «1031)». Кандидат, вырезанный ранее (метка
    // «этап 1)»), в ряд не попадает: приоритет у метки.
    private static string StripEnumMarkers(string text)
    {
        var removed = new List<(int Start, int Length)>();
        var run = new List<(int Start, int Length)>();
        int expected = 1;
        foreach (Match m in EnumMarker.Matches(text))
        {
            if (TryIndex(m, out var value) && value == expected)
            {
                run.Add((m.Index, m.Length));
                expected++;
                continue;
            }
            if (run.Count >= 2)
                removed.AddRange(run);
            run.Clear();
            // Обрыв ряда: с этого же кандидата начинаем новый, если он «1)».
            if (TryIndex(m, out value) && value == 1)
            {
                run.Add((m.Index, m.Length));
                expected = 2;
            }
            else
            {
                expected = 1;
            }
        }
        if (run.Count >= 2)
            removed.AddRange(run);
        if (removed.Count == 0)
            return text;

        var sb = new StringBuilder(text.Length);
        int pos = 0;
        foreach (var (start, length) in removed)
        {
            sb.Append(text, pos, start - pos).Append(' ');
            pos = start + length;
        }
        return sb.Append(text, pos, text.Length - pos).ToString();
    }

    // Индекс перечисления — короткое целое: цифр больше, чем вмещает int, — это
    // не индекс (число длиннее диапазона); TryParse охвачен: «99999999999999)»
    // не должен ронять разбор.
    private static bool TryIndex(Match marker, out int value)
    {
        var digits = marker.Groups[1].Value;
        value = 0;
        return digits.Length <= 10 && int.TryParse(digits, out value);
    }

    // Нормализация до сравнения (тот же порядок, что в QuoteMatcher): пробелы-
    // разделители тысяч внутри числа убрать, десятичную запятую свести к точке,
    // знак-min U+2212 свести к ASCII: «−12» и «-12» — одно число.
    private static string Normalize(string raw)
    {
        var sb = new StringBuilder(raw.Length);
        foreach (var c in raw)
        {
            if (IsThousandsSpace(c))
                continue;
            sb.Append(c == MinusUnicode ? MinusAscii : c);
        }
        return sb.ToString().Replace(',', '.');
    }

    private static bool IsThousandsSpace(char c) => c is ' ' or SpaceNbsp or SpaceNarrow;
}
