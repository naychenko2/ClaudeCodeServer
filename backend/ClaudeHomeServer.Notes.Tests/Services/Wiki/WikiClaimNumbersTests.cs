using System.Diagnostics;
using ClaudeHomeServer.Services.Notes.Wiki;

namespace ClaudeHomeServer.Tests.Services;

// WikiClaimNumbers: числа утверждения и их подтверждение цитатами (S2-2; ADR-039,
// решение 2). Юнит — разбор числа (знак-мин в токене, разделители тысяч ровно по
// 3 цифры, один десятичный разделитель), нормализация («,» → «.», пробелы внутри
// числа убираются, «−» U+2212 → ASCII) и сравнение целыми токенами: «12» не
// подтверждается цитатой с «123», «−12» — цитатой без знака. До разбора из claim и
// из цитат вырезаются: метки сносок [^1] и [^sN] (их цифры не числа утверждения
// и не подтверждение), токены из букв и цифр, в том числе продолжающиеся через
// знак («686d58247» — id коммита, а не «686» и «58247»; «S2-2», «U+2212»,
// «этап-2» — знак после id или слова-метки относится к идентификатору),
// и целые числа сразу после слов-меток («этап 2», «№ 5» — индекс
// раздела, не количество; десятичное после метки — предмет утверждения:
// «Версия 2.28» остаётся числом), и маркеры перечисления из ряда «1) 2) …»
// подряд от 1 длиной ≥ 2 (дефект aa549944; одиночное «5)», «(5)» и ряд, не
// начинающийся с 1, — числа, остаются). Метрики («80%», «16384», «−12 °C»,
// «3 из 6») остаются числами.
// Null claim — пустой результат; null цитат — то же, что пустой
// список: утверждения без цитат подтвердить нечем.
public class WikiClaimNumbersTests
{
    private const char Nbsp = (char)0x00A0;
    private const char Narrow = (char)0x202F;

    // —— Подтверждённые числа: пустой результат ——

    [Fact]
    public void ДесятичнаяЗапятаяСводитсяКТочке()
    {
        // Единственный тест с десятичной запятой: мутация «убрать ,→.» краснит
        // ровно его. «1,18» и «1.18» — одно число после нормализации.
        WikiClaimNumbers.Unconfirmed("темп 1,18 кг", ["1.18 кг/нед"]).Should().BeEmpty();
        // «0,3–0,7»: тире не входит в число — два числа; «0,3» подтверждён цитатой,
        // «0,7» — нет, и в результате он нормализован: запятая свёрнута к точке.
        WikiClaimNumbers.Unconfirmed("0,3–0,7", ["0.3"]).Should().Equal("0.7");
    }

    [Fact]
    public void ПробелыТысячНеМеняютЧисло_подтверждено() =>
        // «176 949» и «176949» — одно число: пробелы-разделители при сравнении убираются.
        WikiClaimNumbers.Unconfirmed("176 949 токенов", ["176949"]).Should().BeEmpty();

    [Theory]
    [InlineData(' ')]
    [InlineData(Nbsp)]
    [InlineData(Narrow)]
    public void РазделительТысяцПодтверждаетсяВЗаписиБезНего(char sep) =>
        // Все три разделителя тысяч (обычный, U+00A0, U+202F) — один и тот же
        // пробел для сравнения: «1<sep>000» подтверждается цитатой «1000».
        WikiClaimNumbers.Unconfirmed($"расход 1{sep}000 Вт", ["1000"]).Should().BeEmpty();

    [Fact]
    public void ЧислоИзЦитатыПодтверждаетЧислоУтверждения() =>
        WikiClaimNumbers.Unconfirmed("урожай 42.5 кг", ["урожай 42.5 кг с сотки"]).Should().BeEmpty();

    // —— Неподтверждённые числа ——

    [Fact]
    public void ДругоеДесятичноеЧисло_неПодтверждено() =>
        WikiClaimNumbers.Unconfirmed("2.28", ["2.27"]).Should().Equal("2.28");

    [Fact]
    public void ЦелоеЧислоНеПодтверждаетсяБолееДлинным() =>
        // Сравнение целыми токенами, не подстрокой: «12» ≠ «123». Мутация
        // «сравнение подстрокой» краснит ровно этот тест.
        WikiClaimNumbers.Unconfirmed("12 шагов", ["123 шага"]).Should().Equal("12");

    [Fact]
    public void ЧислоБезЦитат_неПодтверждено() =>
        WikiClaimNumbers.Unconfirmed("2.28", []).Should().Equal("2.28");

    // —— Знак числа ——

    [Fact]
    public void ОтрицательноеЧислоБезЗнакаВЦитате_неПодтверждено()
    {
        // «−12» (U+2212) и «12» — разные числа: знак входит в число. Мутация
        // «знак не в токене» краснит ровно этот тест (первая проверка).
        WikiClaimNumbers.Unconfirmed("−12 °C", ["12 °C"]).Should().Equal("-12");
        // Оба минуса (ASCII и U+2212) — один и тот же знак после нормализации.
        WikiClaimNumbers.Unconfirmed("−12 °C", ["-12 °C"]).Should().BeEmpty();
        WikiClaimNumbers.Unconfirmed("-12 °C", ["−12 °C"]).Should().BeEmpty();
        // Знак не мешает группам тысяч и десятичной части.
        WikiClaimNumbers.Unconfirmed("расход −1 000 Вт", ["-1000"]).Should().BeEmpty();
        WikiClaimNumbers.Unconfirmed("−2,28", ["-2.27"]).Should().Equal("-2.28");
    }

    [Theory]
    [InlineData("123-456")]
    [InlineData("0.3-0.7")]
    public void ДефисМеждуЧисламиНеЗнак_дваЧисла(string text) =>
        // Знак не стоит после цифры или десятичного разделителя: «123-456» и
        // «0.3-0.7» — два числа, как с тире. Мутация «знак где угодно» краснит
        // ровно этот тест (в результате появился бы «-456» / «-0.7»).
        WikiClaimNumbers.Unconfirmed(text, [text.Split('-')[0]]).Should().Equal(text.Split('-')[1]);

    [Fact]
    public void ДефисПослеЧислаИПробелаНеЗнак_дваЧисла()
    {
        // Пробел перед дефисом, после дефиса пробела нет: «12 -34» — список из двух
        // чисел, а не отрицательное «-34» (дельта-ревью S2-2, п.8). Мутация «вернуть
        // старое условие знака» краснит ровно этот тест: в результате был бы «-34».
        WikiClaimNumbers.Unconfirmed("12 -34", ["12"]).Should().Equal("34");
        // Одиночное «−12 °C» без числа перед знаком — по-прежнему отрицательное.
        WikiClaimNumbers.Unconfirmed("−12 °C", []).Should().Equal("-12");
    }

    // —— Разбор: границы и форма результата ——

    [Fact]
    public void МеткиСносокВырезаютсяИхЦифрыНеЧисла() =>
        // [^1] и [^s2] — маркеры сносок: их цифры не должны считаться числами
        // утверждения, иначе «1» и «2» ушли бы в результат как неподтверждённые.
        WikiClaimNumbers.Unconfirmed("решили так [^1] [^s2]", []).Should().BeEmpty();

    [Fact]
    public void МеткиСносокВЦитатахНеПодтверждаютЧислоClaim() =>
        // Цифры «[^1]» в цитате — маркер сноски, а не число «1»: claim «в 1 случае»
        // ими не подтверждён. Мутация «не вырезать метки из цитат» краснит ровно
        // этот тест.
        WikiClaimNumbers.Unconfirmed("в 1 случае", ["решили так [^1]"]).Should().Equal("1");

    [Fact]
    public void NullClaimПусто_nullЦитатНечемПодтвердить()
    {
        // Null claim — нечего проверять: пустой результат, без NRE.
        WikiClaimNumbers.Unconfirmed(null, ["5"]).Should().BeEmpty();
        WikiClaimNumbers.Unconfirmed(null, null).Should().BeEmpty();
        // Null цитат — то же, что пустой список: подтвердить нечем, число уходит
        // в результат, а не в исключение (дельта-ревью S2-2, п.9).
        WikiClaimNumbers.Unconfirmed("5", null).Should().Equal("5");
    }

    [Fact]
    public void ДиапазонСТире_дваЧисла() =>
        // Тире не входит в число: «0.3» подтверждён цитатой, «0.7» — нет.
        // Тот же разбор, что в кейсе с запятой выше, но без запятых: независим от
        // мутации «,→.».
        WikiClaimNumbers.Unconfirmed("0.3–0.7", ["0.3"]).Should().Equal("0.7");

    [Fact]
    public void ДатаКакЧислоПроверяетсяНаТочномСовпадении() =>
        // «17.08» — одно число; цитата с «17.09» его не подтверждает.
        WikiClaimNumbers.Unconfirmed("замер 17.08", ["замер 17.09"]).Should().Equal("17.08");

    [Fact]
    public void ГруппаПослеПробелаРовноИзТрёхЦифр_иначеЭтоДругоеЧисло() =>
        // «12 3456»: группа из 4 цифр после пробела — не разделитель тысяч.
        // Числа — «12» и «3456»; цитата подтверждает только «12».
        WikiClaimNumbers.Unconfirmed("12 3456", ["12"]).Should().Equal("3456");

    [Fact]
    public void ДвеГруппыТысячОднимЧислом() =>
        // «1 000 000» — одно число (группы ровно по 3 цифры), подтверждено цитатой.
        WikiClaimNumbers.Unconfirmed("1 000 000", ["1000000"]).Should().BeEmpty();

    [Fact]
    public void ДубльЧислаВClaimВРезультатеОдинРаз() =>
        // Порядок — по первому вхождению, без дублей.
        WikiClaimNumbers.Unconfirmed("9 и 9", []).Should().Equal("9");

    [Fact]
    public void ПорядокРезультата_поПервомуВхождениюВClaim() =>
        WikiClaimNumbers.Unconfirmed("сначала 9, потом 7", []).Should().Equal("9", "7");

    // —— Не числа утверждения: идентификаторы и слова-метки (дефект f68d3d82) ——

    [Fact]
    public void ПоловинкиIdСлитыеБуквамиНеЧисла()
    {
        // «686d58247» — id коммита, а не «686» и «58247»; «a1b2» — не «1» и «2»;
        // «100м» — не «100». Мутация «убрать правило слитности с буквами» (вырезание
        // AlnumToken) краснит ровно этот тест: половинки id ушли бы в результат
        // неподтверждёнными числами.
        WikiClaimNumbers.Unconfirmed("коммит 686d58247", []).Should().BeEmpty();
        WikiClaimNumbers.Unconfirmed("слаг a1b2", []).Should().BeEmpty();
        WikiClaimNumbers.Unconfirmed("прогон 100м", []).Should().BeEmpty();
    }

    [Theory]
    // Знак сразу после вырезанного id или после слова-метки относится к
    // идентификатору и не читается знаком числа (дефект f68d3d82, п.3; возврат
    // дельта-ревью S2-2, круг 2): «S2-2» и «s2a-2» не дают «-2» после того, как
    // «S2»/«s2a» вырезаны; «этап-2» — дефис не в разделителях метки, весь токен —
    // идентификатор; «U+2212» — плюс не буквенно-цифровой, весь токен — id, а не
    // число 2212. Мутация «вернуть AlnumToken без знака внутри токена» краснит
    // ровно этот тест: в первых четырёх случаях появился бы «-2», в последнем — «2212».
    [InlineData("S2-2")]
    [InlineData("s2a-2")]
    [InlineData("этап-2")]
    [InlineData("задача S2-2 закрыта")]
    [InlineData("U+2212")]
    public void ЗнакПослеИдентификатораИлиМеткиНеЗнак_чиселНет(string text) =>
        WikiClaimNumbers.Unconfirmed(text, []).Should().BeEmpty();

    [Fact]
    public void ИдентикСоЗнакомНеЕстСледующееОтдельноеЧисло()
    {
        // Охрана границы: идентификатор присоединяет знак и число сразу после него,
        // но не простирается дальше — «16384» через слово остаётся числом
        // утверждения.
        WikiClaimNumbers.Unconfirmed("id S2-2 и 16384", []).Should().Equal("16384");
    }

    [Theory]
    // Каждая метка константы LabelWords плюс «№» и «#», в падежной форме и с
    // заглавной буквы («Этап 2» в начале предложения).
    [InlineData("для этапа 2 заменен")]
    [InlineData("шаг 3")]
    [InlineData("пункт 4")]
    [InlineData("версии 5")]
    [InlineData("вариант 6")]
    [InlineData("волна 7")]
    [InlineData("раздел 8")]
    [InlineData("№ 5")]
    [InlineData("#10")]
    [InlineData("Этап 2")]
    public void ЦелоеЧислоСразуПослеСловаМеткиНеПроверяется(string text) =>
        // «этап 2», «№ 5» — индекс раздела или последовательности, а не количество:
        // вырезается из текста до разбора. Мутация «убрать вырезание LabelNumber»
        // краснит ровно этот тест.
        WikiClaimNumbers.Unconfirmed(text, []).Should().BeEmpty();

    [Fact]
    public void МеткаНеОтсекаетЧислоСДробнойЧастью()
    {
        // Метка отсекает только целое число-индекс: «Версия 2.28» — десятичное
        // число после метки — предмет утверждения (как метрика), а не индекс
        // раздела: оно остаётся числом утверждения и не подтверждается «2.27».
        // Мутация «убрать (?![0-9.,\p{L}]) за меткой» краснит ровно этот тест:
        // «2.28» было бы вырезано как индекс.
        WikiClaimNumbers.Unconfirmed("Версия 2.28 вышла вчера", ["Версия 2.27 вышла вчера"]).Should().Equal("2.28");
    }

    [Fact]
    public void ЧислоПослеМеткиВЦитатеНеПодтверждаетЧислоClaim()
    {
        // Симметрия: тот же фильтр применён и к цитатам — «5» из «этап 5» не
        // подтверждает число claim: оно индекс, а не количество.
        WikiClaimNumbers.Unconfirmed("5 предметов", ["этап 5"]).Should().Equal("5");
    }

    // —— Маркеры перечисления «1) 2) …» (дефект aa549944) ——

    [Fact]
    public void МаркерыРядаПеречисленияВырезаютсяИхЦифрыНеЧисла()
    {
        // «1) 2) 3)» — маркеры перечисления, а не числа утверждения: иначе «1»,
        // «2», «3» уходили бы в «Входящие» неподтверждёнными (дефект aa549944).
        // «103» и «109» — настоящие числа claim, остаются и не подтверждены.
        // Мутация «убрать StripEnumMarkers» краснит этот тест (с ещё четырьмя
        // тестами ряда).
        WikiClaimNumbers.Unconfirmed("Аргументы: 1) рост 2) спад 3) рост 103–109%", []).Should().Equal("103", "109");
    }

    [Theory]
    // Одиночные маркеры и ряд, не начинающийся с 1, — консервативно остаются
    // числами: вырезается только ряд «1) 2) …» подряд от 1 длиной ≥ 2.
    [InlineData("срок до 5) лет", "5")]
    [InlineData("индекс (5) вырос", "5")]
    [InlineData("1) только", "1")]
    [InlineData("2) а 3) б", "2", "3")]
    public void ОдиночныйМаркерИРядНеОтЕдиницыОстаютсяЧислами(string text, params string[] expected) =>
        WikiClaimNumbers.Unconfirmed(text, []).Should().Equal(expected);

    [Fact]
    public void МаркерВнутриСловаНеМаркер_чиселНет()
    {
        // «S2)» — после буквы: не маркер и не число (дефект f68d3d82, токен с
        // буквой — идентификатор). «(5)» — после скобки: не маркер, но число.
        WikiClaimNumbers.Unconfirmed("id S2) закрыта", []).Should().BeEmpty();
    }

    [Fact]
    public void РядИзДесятиМаркеровВырезаетсяДоДесяти()
    {
        // Ряд доходит до «10)» — многзначный индекс тоже маркер; вырезание идёт
        // по фактической длине токена, соседние числа не склеиваются.
        WikiClaimNumbers.Unconfirmed("1) a 2) b 3) c 4) d 5) e 6) f 7) g 8) h 9) i 10) j", []).Should().BeEmpty();
    }

    [Fact]
    public void МаркерПослеРядаОстаётсяЧислом()
    {
        // «5)» после ряда 1)–2) — вне ряда (обрыв на 5): ряд вырезан, «5» —
        // число утверждения, консервативно уходит к человеку.
        WikiClaimNumbers.Unconfirmed("1) a 2) b 5) c", []).Should().Equal("5");
    }

    [Theory]
    // Обрванный ряд — не перечисление: «3)» вместо 2) обрывает ряд на длине 1,
    // «103)» перед рядом — не его начало; ряд 1)–2) вырезан, «103» остаётся
    // числом и не склеивается с вырезанным «1)» в «1031)».
    [InlineData("1) a 3) b", "1", "3")]
    [InlineData("103) 1) a 2) b", "103")]
    public void ОбрванныйРядНеПеречисление_илиРядПослеЧисла(string text, params string[] expected) =>
        WikiClaimNumbers.Unconfirmed(text, []).Should().Equal(expected);

    [Fact]
    public void МаркерыРядаВЦитатеНеПодтверждаютЧислоClaim()
    {
        // Симметрия с метками: тот же фильтр и к цитатам — «3» из ряда «1) 2) 3)»
        // в цитате — маркер перечисления, а не число: claim «3 предмета» им не
        // подтверждён. Мутация «не вырезать ряд из цитат» краснит ровно этот тест:
        // «3)» ложно подтвердил бы «3».
        WikiClaimNumbers.Unconfirmed("3 предмета", ["1) а 2) б 3) в"]).Should().Equal("3");
    }

    [Fact]
    public void МетрикиОстаютсяЧисламиУтверждения()
    {
        // Новые правила не должны вымыть метрики: «%» и «°» — не буквы, «из» — не
        // метка, «16384» — чисто цифровой токен.
        WikiClaimNumbers.Unconfirmed("80% зелёных", []).Should().Equal("80");
        WikiClaimNumbers.Unconfirmed("3 из 6", []).Should().Equal("3", "6");
        WikiClaimNumbers.Unconfirmed("16384", []).Should().Equal("16384");
        WikiClaimNumbers.Unconfirmed("−12 °C", []).Should().Equal("-12");
    }

    // —— Бюджет: регулярное выражение без катастрофического отката ——

    [Theory]
    // Смешанные группы разной длины, сплошная цифровая полоса и сплошной ряд
    // кандидатов-маркеров: все строки 10 000 символов.
    [InlineData("123 45 6", 1250)]
    [InlineData("7", 10000)]
    [InlineData("1) ", 2500)]
    public void СтрокаИзДесятиТысячСимволовОбрабатываетсяБезКатастрофическогоОтката(string unit, int repeat)
    {
        // Ровно 10 000 символов: группы разной длины («123», «45», «6»), смежные
        // цифровые подряды склеиваются в длинные числа, либо одна сплошная полоса —
        // самый длинный токен, либо 2500 кандидатов «1)» (обрванный ряд: ни один
        // не вырезается, все остаются числами) — самый частый токен для
        // StripEnumMarkers. 10 000 заведомо больше лимита claim (600): проверяется
        // устойчивость разбора, а не типичный вход. Порог щадящий (1 с): ловит
        // катастрофический откат (десятки секунд), а не дрожание таймера на CI.
        var s = string.Concat(Enumerable.Repeat(unit, repeat));
        var sw = Stopwatch.StartNew();
        var result = WikiClaimNumbers.Unconfirmed(s, []);
        sw.Stop();
        result.Should().NotBeEmpty();
        sw.ElapsedMilliseconds.Should().BeLessThan(1000);
    }
}
