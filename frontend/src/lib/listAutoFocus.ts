import { useIsTouch } from './breakpoints';

// Правило автофокуса для полей-входов в СПИСОК (поиск, фильтр, палитра команд).
// На touch-устройстве такой автофокус мгновенно поднимает экранную клавиатуру, и она
// закрывает пол-экрана с самим списком — ради которого поле и открыли. Гейт именно по
// pointer: coarse, а не по ширине: планшет шире 600px страдает ровно так же.
//
// Поля, ради которых человек сам нажал действие (создание заметки/базы, переименование
// файла, ввод пароля), автофокус СОХРАНЯЮТ: там клавиатура ожидаема и есть смысл действия.
// Поэтому гейт живёт здесь, а не внутри TextField/IconField — те же контролы работают
// в inline-переименовании, и безусловная проверка внутри контрола сломала бы его.
export function useListAutoFocus(): boolean {
  return !useIsTouch();
}
