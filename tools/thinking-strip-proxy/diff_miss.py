#!/usr/bin/env python3
# Разбор промахов prefix cache по дампу тел (`PRUNE_DUMP_DIR` прокси).
#
# Зачем: в живом прогоне 2026-09-23 четыре промаха из шести пришлись на НЕПОДВИЖНУЮ границу
# прунинга — из кэша бралась ровно системная часть (~13k), то есть история расходилась с
# первого сообщения, а цена каждого промаха (71–184 с) превышала цену самого прунинга.
# Размеры в отладочной строке на такой вопрос не отвечают: разошлись байты, и найти их можно
# только сравнением соседних тел одной сессии.
#
# Что делает: находит запросы, где `cache_read` меньше половины промпта, и для каждого
# показывает, ЧЕМ его тело отличается от предыдущего запроса той же сессии — системная часть,
# вставка/удаление сообщения, замена содержимого — с первым расходящимся символом.
#
# Главный вывод инструмента — не сам diff, а СВЕРКА: сколько токенов тела совпадает с прошлым
# запросом против того, сколько движок взял из кэша. Совпало ровно столько, сколько взято, —
# промах объясняется телом (виноват CLI или сам прокси). Тело совпадает намного дальше —
# содержимое ни при чём, блоки вытеснены из KV-кэша, и лечится это не прокси.
#
#   python3 diff_miss.py /tmp/prune-dump [--порог 0.5] [--сессия <id>] [--все]
import argparse
import gzip
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import proxy  # noqa: E402  — мерка токенов берётся у прокси, дублировать её нельзя

# Доля промпта из кэша, ниже которой запрос считается промахом. Половина — не «чуть хуже
# обычного»: на живом прогоне здоровые ходы давали 98–99 %, а промахи 0–13 %, между ними
# пусто. Порог посередине и ловит ровно вторую группу.
ПОРОГ_ПРОМАХА = 0.5
ОКНО = 90  # сколько символов вокруг расхождения показывать


def _канон(значение):
    """Сериализация для сравнения: порядок ключей не важен, порядок блоков и текст — важны."""
    return json.dumps(значение, ensure_ascii=False, sort_keys=True)


def _первое_расхождение(a, b):
    """Индекс первого расходящегося символа двух строк (или None, если равны)."""
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            return i
    return None if a == b else min(len(a), len(b))


def _окно(строка, позиция):
    начало = max(0, позиция - ОКНО // 2)
    кусок = строка[начало:позиция + ОКНО // 2]
    return ("…" if начало else "") + кусок.replace("\n", "\\n") + ("…" if len(строка) > позиция + ОКНО // 2 else "")


def сравнить(прошлое, текущее):
    """Чем тело `текущее` отличается от `прошлое`. Возвращает словарь разбора.

    Поля: `вид` — что случилось (`системная`, `вставка`, `удаление`, `замена`, `хвост`,
    `совпало`), `индекс` — номер первого расходящегося сообщения, `совпало_сообщений` —
    сколько сообщений от начала идентичны, плюс человекочитаемые подробности в `строки`.

    Разбор один на запрос, а не список всех отличий: prefix cache обрывается на ПЕРВОМ
    расхождении, и всё, что дальше, на его судьбу уже не влияет.
    """
    строки = []
    сис_а = _канон([прошлое.get("system"), прошлое.get("tools")])
    сис_б = _канон([текущее.get("system"), текущее.get("tools")])
    if сис_а != сис_б:
        поз = _первое_расхождение(сис_а, сис_б)
        строки += [f"системная часть разошлась на символе {поз} из {len(сис_б)}",
                   f"  было:  {_окно(сис_а, поз)!r}",
                   f"  стало: {_окно(сис_б, поз)!r}"]
        return {"вид": "системная", "индекс": -1, "совпало_сообщений": 0, "строки": строки}

    а = [_канон(m) for m in (прошлое.get("messages") or [])]
    б = [_канон(m) for m in (текущее.get("messages") or [])]
    i = 0
    while i < len(а) and i < len(б) and а[i] == б[i]:
        i += 1
    if i == len(а) and len(б) >= len(а):
        строки.append(f"расхождений нет: дописан хвост, +{len(б) - len(а)} сообщений "
                      f"(было {len(а)}, стало {len(б)})")
        return {"вид": "хвост" if len(б) > len(а) else "совпало", "индекс": len(а),
                "совпало_сообщений": len(а), "строки": строки}

    # Совпадающий суффикс: по нему вставка и удаление отличаются от замены содержимого.
    хвост = 0
    while (хвост < len(а) - i and хвост < len(б) - i
           and а[len(а) - 1 - хвост] == б[len(б) - 1 - хвост]):
        хвост += 1
    сдвиг = len(б) - len(а)
    if сдвиг > 0 and хвост >= len(а) - i:
        вид, строки = "вставка", строки + [
            f"вставлено {сдвиг} сообщений перед #{i} (всё остальное совпадает)",
            f"  вставлено: {_окно(б[i], 0)!r}"]
    elif сдвиг < 0 and хвост >= len(б) - i:
        вид, строки = "удаление", строки + [
            f"удалено {-сдвиг} сообщений с позиции #{i} (всё остальное совпадает)",
            f"  удалено: {_окно(а[i], 0)!r}"]
    else:
        поз = _первое_расхождение(а[i], б[i]) or 0
        вид, строки = "замена", строки + [
            f"сообщение #{i} ({json.loads(б[i]).get('role')}) изменилось: первый расходящийся "
            f"символ {поз} из {len(б[i])}",
            f"  было:  {_окно(а[i], поз)!r}",
            f"  стало: {_окно(б[i], поз)!r}"]
        if len(а) != len(б):
            строки.append(f"  плюс изменилось число сообщений: {len(а)} → {len(б)}")
    return {"вид": вид, "индекс": i, "совпало_сообщений": i, "строки": строки}


def токенов_совпало(тело, сообщений):
    """Оценка совпавшего префикса в токенах: системная часть плюс первые N сообщений.

    Меркой прокси, а не своей: у неё отдельные коэффициенты на историю, системную часть и
    base64-подписи, и вторая копия этой арифметики разошлась бы с первой.
    """
    msgs = (тело.get("messages") or [])[:сообщений]
    return proxy.estimate_tokens(proxy._context_chars(msgs), proxy._system_chars(тело),
                                 proxy._signature_chars(msgs))


def вердикт(совпало, cache_read, вид="замена"):
    """«ТЕЛО» или «ВЫТЕСНЕНИЕ» — главный ответ разбора, с цифрами обоих слагаемых.

    Логика в две ступени, потому что и причин две, и они складываются:

    1. Нашёл ли diff расхождение вообще. Тела расходятся — кэш обязан оборваться там, и
       причина промаха названа: тело (правка CLI или самого прокси, например сдвиг границы).
       Тела совпадают целиком, а из кэша крохи — объяснять нечем, кроме вытеснения блоков.
    2. Сколько кэш недодал СВЕРХ расхождения. Отдать больше, чем совпадает по тексту, он не
       может, а вот меньше — запросто: столько блоков успели вытеснить. Запас (20 % плюс 3000
       токенов) покрывает погрешность мерки и округление движка до блока.
    """
    if cache_read is None:
        return "цифр кэша нет — движок не прислал usage"
    недодано = совпало - cache_read
    # Порог считается от СОВПАВШЕГО, а не от взятого из кэша: при `cache_read` около нуля
    # доля от него вырождается, а вопрос-то ровно в том, сколько кэш недодал против текста.
    вытеснение = недодано > max(3000, совпало * 0.2)
    if вид in ("хвост", "совпало"):
        if not вытеснение:
            return (f"НОРМА: кэш отдал весь совпавший префикс (~{совпало} ток, взято "
                    f"{cache_read}) — низкая доля лишь от жирного нового хвоста, а не от промаха")
        return (f"ВЫТЕСНЕНИЕ: тела совпадают целиком (~{совпало} ток), а из кэша взято "
                f"{cache_read} ток — расхождению взяться неоткуда, блоки вытеснены из KV-кэша")
    if вытеснение:
        return (f"ТЕЛО + ВЫТЕСНЕНИЕ: расхождение обрывает кэш на ~{совпало} ток, но движок "
                f"отдал лишь {cache_read} — ещё ~{недодано} ток совпадавшего префикса вытеснено")
    return (f"ТЕЛО: совпало ~{совпало} ток, из кэша {cache_read} ток — движок отдал всё, что "
            f"совпало, промах объясняется расхождением выше")


# --- Чтение дампа -----------------------------------------------------------------------------


def загрузить(каталог):
    """Записи дампа по возрастанию номера: мета плюс путь к телу. Тело читается по требованию."""
    записи = []
    for имя in sorted(os.listdir(каталог)):
        if not имя.endswith(".meta.json"):
            continue
        with open(os.path.join(каталог, имя), encoding="utf-8") as f:
            мета = json.load(f)
        мета["мета_файл"] = имя
        мета["тело_файл"] = os.path.join(каталог, мета.get("body") or "")
        записи.append(мета)
    return sorted(записи, key=lambda з: з.get("seq") or 0)


def тело(запись):
    with gzip.open(запись["тело_файл"], "rb") as f:
        return json.load(f)


def служебный(запись):
    """Запрос без генерации: `count_tokens`, `/v1/models`, health-проба.

    Их CLI шлёт десятками, KV-кэша они не касаются и промахом быть не могут (usage у них нет
    вовсе). В разборе они только шум — и в таблице, и в счёте «сколько чужих запросов прошло
    между ходами», где из-за них нагрузка на движок выглядела бы больше, чем была.
    """
    путь = (запись.get("path") or "").split("?")[0]
    return not путь.endswith("/v1/messages")


def ключ_сессии(запись):
    """По какому признаку группировать запрос, если заголовка `X-CCS-Session` нет.

    Заголовок ставит бэкенд, и в боевой сборке 2026-09-22 его ещё нет (проверено: строки
    `X-CCS-Session` в `/opt/ccs/app/ClaudeHomeServer.Llm.dll` нет вовсе). Без него в дамп
    валятся вперемешку ходы агента и фоновые одиночные действия продукта, и «предыдущим
    запросом» хода оказалось бы фоновое действие — разбор сравнивал бы несравнимое.

    Поэтому запасной признак — есть ли у запроса системная часть: у хода агента это промпт
    плюс определения инструментов, у фонового one-shot её нет вовсе. Грубо, но ровно те две
    группы и разделяет. Появится заголовок — он точнее, и берётся он.
    """
    if запись.get("session"):
        return запись["session"]
    if "группа" not in запись:
        try:
            запись["группа"] = "ход" if proxy._system_chars(тело(запись)) else "фон"
        except Exception:
            запись["группа"] = "фон"
    return запись["группа"]


def цифры(запись):
    """`(промпт, из кэша, доля)` по usage записи; доля None, если цифр нет.

    Семантик `input_tokens` у роутера vLLM ДВЕ, и различать их обязательно (снято живьём
    2026-09-23): в `message_start` там только то, что прошло мимо кэша (по-Anthropic'овски), а
    в финальном `message_delta` — ВЕСЬ промпт, кэш включительно. Сложи слагаемые вслепую — и
    здоровый ход с 96 % попаданий покажется промахом на 48 %; ровно так первый разбор и
    соврал. Признак полной формы простой: `input_tokens` не меньше `cache_read`.
    """
    usage = запись.get("usage") or {}
    вход = usage.get("input_tokens") or 0
    чтение = usage.get("cache_read_input_tokens")
    if not isinstance(чтение, int):
        return вход or None, None, None
    промпт = вход if вход >= чтение else (
        вход + чтение + (usage.get("cache_creation_input_tokens") or 0))
    if not промпт:
        return None, чтение, None
    return промпт, чтение, чтение / промпт


def соседи(записи, запись, прошлая):
    """Чужие запросы, пришедшие между прошлым запросом этой сессии и этим.

    Проверяемая ими гипотеза — вытеснение из KV-кэша побочными запросами: продукт ходит на ту
    же локальную модель фоновыми одиночными запросами, и в живом прогоне два промаха из четырёх
    пришли через 100–130 мс после такого запроса.
    """
    с, по = (прошлая or запись).get("epoch") or 0, запись.get("epoch") or 0
    return [з for з in записи
            if з is not запись and з is not прошлая and с <= (з.get("epoch") or 0) <= по]


def разобрать(каталог, порог=ПОРОГ_ПРОМАХА, сессия=None, показать_все=False, вывод=sys.stdout):
    записи = загрузить(каталог)
    служебных = sum(1 for з in записи if служебный(з))
    записи = [з for з in записи if not служебный(з)]
    if сессия:
        записи = [з for з in записи if ключ_сессии(з) == сессия]
    печать = lambda *a: print(*a, file=вывод)  # noqa: E731
    печать(f"Дамп: {каталог}, запросов к модели {len(записи)}"
           + (f" (плюс {служебных} служебных: count_tokens, /v1/models — пропущены)"
              if служебных else ""))
    по_сессиям = {}
    for з in записи:
        по_сессиям.setdefault(ключ_сессии(з), []).append(з)
    печать("Сессии: " + ", ".join(f"{к} — {len(v)} запросов" for к, v in по_сессиям.items())
           + ("" if any(з.get("session") for з in записи)
              else "  (заголовка X-CCS-Session нет — группировка по наличию системной части)"))

    if показать_все:
        печать("\n№     время          сессия        промпт    из кэша   ttfb")
        for з in записи:
            промпт, чтение, доля = цифры(з)
            печать(f"{з.get('seq'):<5} {(з.get('ts') or '')[11:]:<14} "
                   f"{str(ключ_сессии(з))[:12]:<13} {промпт or 0:>8} "
                   f"{(f'{доля:.0%}' if доля is not None else '—'):>9} "
                   f"{з.get('ttfbSeconds') or 0:>6}")

    промахов = 0
    for индекс, з in enumerate(записи):
        промпт, чтение, доля = цифры(з)
        if доля is None or доля >= порог:
            continue
        промахов += 1
        печать(f"\n=== промах #{промахов}: запрос {з.get('seq')} в {з.get('ts')}, "
               f"промпт {промпт} ток, из кэша {чтение} ({доля:.1%}), "
               f"ждали {з.get('ttfbSeconds')} с")
        печать(f"    сессия {ключ_сессии(з)}, upstream {з.get('upstream')},"
               f" обрезано блоков {з.get('blocks')}, тело {з.get('bodyBytes')} Б")
        прошлая = next((p for p in reversed(записи[:индекс])
                        if ключ_сессии(p) == ключ_сессии(з)), None)
        if прошлая is None:
            печать("    предыдущего запроса этой сессии в дампе нет — сравнивать не с чем "
                   "(первый ход чата или фоновое одиночное действие продукта)")
            continue
        разбор = сравнить(тело(прошлая), тело(з))
        граница = (f"граница НЕПОДВИЖНА ({прошлая.get('blocks')} блоков)"
                   if прошлая.get("blocks") == з.get("blocks")
                   else f"граница СДВИНУЛАСЬ: {прошлая.get('blocks')} → {з.get('blocks')} блоков")
        печать(f"    прошлый запрос той же сессии: {прошлая.get('seq')} в {прошлая.get('ts')}"
               f"; {граница}")
        for строка in разбор["строки"]:
            печать("    " + строка)
        совпало = токенов_совпало(тело(з), разбор["совпало_сообщений"])
        печать("    " + вердикт(совпало, чтение, разбор["вид"]))
        рядом = соседи(записи, з, прошлая)
        if рядом:
            сумма = sum(цифры(с)[0] or 0 for с in рядом)
            печать(f"    между запросами прошло {len(рядом)} чужих запросов на {сумма} ток "
                   f"промпта: " + ", ".join(f"{с.get('seq')}@{(с.get('ts') or '')[11:]}"
                                            f"({цифры(с)[0] or 0})" for с in рядом[:6]))
        else:
            печать("    чужих запросов между ними не было")
    if not промахов:
        печать(f"\nПромахов ниже {порог:.0%} в дампе нет.")
    return промахов


def main(аргументы=None):
    p = argparse.ArgumentParser(description="Разбор промахов prefix cache по дампу тел прокси")
    p.add_argument("каталог", help="папка PRUNE_DUMP_DIR")
    p.add_argument("--порог", type=float, default=ПОРОГ_ПРОМАХА,
                   help="доля промпта из кэша, ниже которой это промах (по умолчанию 0.5)")
    p.add_argument("--сессия", default=None, help="разбирать только эту сессию")
    p.add_argument("--все", action="store_true", help="таблица всех запросов дампа")
    a = p.parse_args(аргументы)
    разобрать(a.каталог, порог=a.порог, сессия=a.сессия, показать_все=a.все)
    return 0


if __name__ == "__main__":
    sys.exit(main())
