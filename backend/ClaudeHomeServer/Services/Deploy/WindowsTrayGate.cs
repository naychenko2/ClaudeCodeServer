using Microsoft.Extensions.Logging;

namespace ClaudeHomeServer.Services.Deploy;

/// <summary>
/// Разговор с треем через именованное событие — ровно то же, что делает сам раннер, когда
/// второй запуск его exe просит работающий экземпляр о действии (Program.Signal): открыть
/// существующее событие и поставить его.
///
/// Почему НЕ запускаем ClaudeServerTray.exe с ключом, хотя скилл из чата делает именно так.
/// При живом трее разницы нет — процесс-сигнальщик ставит событие и умирает. А вот при мёртвом
/// разница катастрофическая: ключ в этом случае лишь пишется в лог как проигнорированный, и
/// процесс идёт дальше поднимать ПОЛНОЦЕННЫЙ трей — дочерний нашему. Тот при старте гасит
/// «осиротевшие» инстансы продукта по совпадению полного пути, то есть собственного родителя,
/// и поднимает свой. Одно нажатие кнопки на чужой машине ставило бы там постоянный супервизор
/// поверх чужого инстанса. Со ставкой события такого сценария нет вовсе: нечего запускать.
///
/// Побочная выгода — исчезает щель между «проверили, что трей жив» и «запустили exe»: здесь
/// проверка и есть сама операция.
///
/// Ограничение: событие живёт в сессионном пространстве имён (без префикса Global\), поэтому
/// связь работает, пока продукт и трей — в одной интерактивной сессии Windows. Это нынешняя
/// топология: трей сам запускает продукт. Другая (продукт как служба) даст безопасный отказ
/// «трей не отвечает» — но искать причину без этой строчки будут долго.
/// </summary>
public sealed class WindowsTrayGate(ILogger<WindowsTrayGate> log) : ITrayGate
{
    public bool IsAlive(string eventName) => WithHandle(eventName, _ => true);

    public bool Signal(string eventName) => WithHandle(eventName, h => { h.Set(); return true; });

    // Хэндл открываем и закрываем на каждый вызов, НИКОГДА не кэшируем в поле. Именованный
    // объект ядра жив, пока его держит хоть кто-то: сохранённый хэндл пережил бы смерть трея,
    // проверка стала бы вечно успешной, и кнопка рапортовала бы об отправленной команде,
    // которую никто не слушает.
    private bool WithHandle(string eventName, Func<EventWaitHandle, bool> action)
    {
        if (!OperatingSystem.IsWindows() || string.IsNullOrWhiteSpace(eventName)) return false;

        try
        {
            // TryOpenExisting возвращает false на «нет такого объекта», но на чужой ACL бросает
            // UnauthorizedAccessException — для нас оба случая означают одно: достучаться нельзя.
            if (!EventWaitHandle.TryOpenExisting(eventName, out var handle)) return false;
            using (handle) return action(handle);
        }
        catch (Exception ex)
        {
            log.LogWarning(ex, "Не удалось открыть событие трея {EventName}.", eventName);
            return false;
        }
    }
}
