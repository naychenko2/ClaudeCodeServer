namespace ClaudeHomeServer.Services.Turn;

// Два узких шва слоя персоны (Этап 5, узкие швы Turn). Оба живут в Core на стороне
// ПОТРЕБИТЕЛЯ (namespace слоя промпта), реализации — тонкие адаптеры в Main
// (Services/Composition/PromptSeamAdapters.cs) поверх соответствующих вертикалей.
// Прецедент — ISessionDirectory/ITaskLookup: контракт в спине, реализация в Main.
//
// Оба опциональны (`?` у зависимости контрибьютора): без них слой персоны деградирует
// к минимуму, а не падает — так же, как прежде вёл себя `SkillsService?`.

// Промпт файлового .md-агента проекта — fallback слоя персоны, когда персоны у чата нет,
// а AgentName задан. Единственный член: контрибьютор звал у SkillsService ровно его.
public interface IAgentPromptSource
{
    string? GetAgentSystemPrompt(string projectRootPath, string agentFileName);
}

// Блок «Командные механики» для руководителя проекта: доступные механики (каталог Team,
// отфильтрованный по установленным умениям Skills) плюс протокол маркера. null —
// предложить нечего.
//
// Шов взят по РЕЗУЛЬТАТУ, а не по данным, потому что слой персоны спрашивал у двух
// вертикалей сразу: имена умений (три метода SkillsService, каждый со своим типом
// SkillInfo) он собирал только затем, чтобы отдать их фильтром в статический каталог
// Team. Решение «предлагать ли механики вообще» (персона чата — дефолт-персона проекта)
// осталось в контрибьюторе: это его гейт, а не дело каталога.
public interface ITeamMechanicsBlockSource
{
    string? BuildBlock();
}
