// берёт из ответа; до того единственный потребитель ключа — openMeetingNote ниже.
export function openMeetingNote(_id: string): void {
  // Ф4.б+Ф4.в: здесь будет запрос содержимого по id и открытие просмотрщика.
  showToast('Встреча', 'Файл встречи пока недоступен в приложении', 'info');
}
