// Отказ включить режим чата (автопилот / «Командная реализация»), когда в том же чате уже
// активен второй, несовместимый с ним (B4 приёмки): промпт получал бы разом «сам файлы не
// правишь, работа только через задачи» и «немедленно запусти автономное исполнение» — модель
// лезет в правку, получает отказ инструмента, а активный цикл «до готово» долбит «Продолжай»
// все итерации впустую. Текст — человеку, показывается как есть.
public sealed class SessionModeConflictException(string message) : Exception(message);
