namespace ClaudeHomeServer.Services.ChildMode;

/// <summary>
/// Детские тексты отказа хода по состоянию И3 (KM-B5d, ADR-041 §И3): текст идёт в ошибку хода,
/// его читает ребёнок — поэтому в нём нет технических слов («лимит», «бюджет», «state», кодов
/// ручки нет вовсе). Тон — тот же, что у заставки фронта (ChildTimeUpScreen): спокойный конец,
/// а не упрёк.
///
/// Тексты волны 1: единственное пространство — «Уроки» (ChildSpaces.Lessons), поэтому в тексте
/// есть слово «уроки». Студия волны 2 добавит свою формулировку той же правкой этого словаря —
/// состояния и их порядок при этом не меняются (ключ — состояние, не пространство).
/// </summary>
public static class ChildLimitTexts
{
    /// <summary>Текст отказа по состоянию. Warn и Ok отказа не имеют (ход идёт).</summary>
    public static string For(ChildState state) => state switch
    {
        ChildState.TimeUp => "На сегодня уроки закончились. Отдохни и возвращайся завтра.",
        ChildState.OutOfWindow => "Сейчас уроки отдыхают. Вернись, когда они снова начнутся.",
        ChildState.BudgetExhausted => "На сегодня всё по деньгам закончилось. Позови взрослого.",
        ChildState.RulesPending => "Сначала надо договорить о правилах. Позови взрослого — правила вы ставите вместе.",
        _ => "Сейчас не могу начать. Позови взрослого.",
    };

    /// <summary>
    /// Отказ, когда сам расчёт не читаемый (профиль не прошёл проверку уже после сверки И1-бис):
    /// тот же тон, что у состояний, — ребёнок не видит внутреннего имени ошибки.
    /// </summary>
    public const string Uncheckable = "Настройки детского режима сейчас не читаются. Позови взрослого.";
}
