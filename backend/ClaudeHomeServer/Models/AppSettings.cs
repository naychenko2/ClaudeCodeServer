namespace ClaudeHomeServer.Models;

// Настройки инстанса. Редактируемые поля НУЛЛАБЕЛЬНЫ намеренно: PUT /api/settings работает
// как патч — отсутствующее (null) поле означает «не трогать». Иначе экран, знающий лишь про
// свою настройку, слал бы объект целиком и затирал соседние своим устаревшим снимком
// (тумблер брифа так откатывал ClaudeBilling). Get всегда возвращает поля заполненными.
public class AppSettings
{
    public string DefaultProjectsPath { get; set; } = "";
    // Тип доступа к Claude: "subscription" (подписка — стоимость показывается как ≈ API-эквивалент,
    // отдельно не списывается) | "api" (оплата по API-ключу — реальная цена). По умолчанию подписка.
    public string? ClaudeBilling { get; set; }
    // Присылать ли утренний бриф по расписанию (см. DailyBriefingService). Настройка инстанса,
    // а не пользователя: бриф — фоновое действие, и включает его админ в «Фоновых задачах».
    // Выключение гасит только автозапуск планировщиком — собрать бриф кнопкой можно всегда.
    // Поля нет в app-settings.json (файл записан до появления настройки) — считаем включённым.
    public bool? DailyBriefingEnabled { get; set; }
    // ЛЕГАСИ: одиночная «модель по умолчанию» до перехода на слоты (v2). Поле осталось только
    // ради миграции старых app-settings.json: при загрузке непустое значение переезжает в
    // ModelTierMedium и поле очищается. Новый код читает ТОЛЬКО слоты.
    public string? DefaultChatModel { get; set; }
    // Слоты «сильная/средняя/слабая» — три именованные модели инстанса (id модели любого
    // настроенного провайдера). На них ссылаются назначения мест (LocalActionOverridesStore,
    // значения "tier:strong|medium|weak") и дефолты каталога. null/пусто = слот не задан:
    // место, ссылающееся на него, уходит на дефолт CLI. Патч-семантика как у остальных полей:
    // null = не трогать, "" = сознательная очистка слота.
    public string? ModelTierStrong { get; set; }
    public string? ModelTierMedium { get; set; }
    public string? ModelTierWeak { get; set; }
}
