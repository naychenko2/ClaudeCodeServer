// Прилипание ленты чата к низу после события прокрутки (hooks/useChatScroll).
// Отклеивает ленту живой жест (колесо, тач, клавиши, полоса прокрутки), а программные сдвиги
// геометрии — нет: композер домерился, лента дорендерилась. Но сдвиг ВВЕРХ, после которого лента
// не у низа, — всегда чья-то воля, даже без жеста: scrollIntoView карточки, фокус по Tab,
// переход к сообщению. Рост контента и сжатие области прокрутки scrollTop не уменьшают, а
// сжатие ленты прижимает его к новому концу — то есть к низу. Без этого правила лента,
// подведённая к карточке программно, оставалась «приклеенной», и первый же рост карточки
// (протяжка по волне «Звука» выводит ряд «Обрезать / Перегенерировать кусок») уносил её в конец.

export interface ScrollSample {
  atBottom: boolean;   // лента у низа после сдвига
  gesture: boolean;    // идёт жест пользователя
  movedUp: boolean;    // scrollTop уменьшился с прошлого события
}

export function stickAfterScroll(stuck: boolean, s: ScrollSample): boolean {
  if (s.atBottom) return true;
  if (s.gesture || s.movedUp) return false;
  return stuck;
}
