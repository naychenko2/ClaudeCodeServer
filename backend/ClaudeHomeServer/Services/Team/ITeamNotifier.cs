namespace ClaudeHomeServer.Services.Team;

/// <summary>
/// Шов «ядро сессии → штаб» (этап 4, шаг 2б плана выноса штаба, §5(3) и §5(4) плана
/// session-core-split-2026-09.md). Четыре крючка уведомления и один запрос, которыми ядро
/// сессии сообщает вертикали штаба о событиях приёма и середины хода.
///
/// В этой волне реализован внутри <see cref="Services.SessionManager"/> как обёртка над
/// прежними приватными методами (поведение не меняется); в шаге 2г реализация переедет
/// в вертикаль штаба целиком, ядро будет получать <see cref="ITeamNotifier"/> через DI.
///
/// Не делегат — отличается от 10 Func-полей <c>LlmSessionContext</c> по трём осям:
/// направление владения (ядро реализует интерфейс, не заполняет чужие поля лямбдами),
/// видимость сторожам границ (Implements-ребро видно рефлексии и IL-скану) и дисциплина
/// роста (метод в поименованном контракте — review-абельная единица, поле record'а — нет).
/// </summary>
internal interface ITeamNotifier
{
    /// <summary>
    /// §5(3) №12. Синхронный крючок «человек написал в чат» — сброс бюджета итерации и
    /// вход в план-режим (Э5). Делается на приёме сообщения, ДО очереди: иначе вводная,
    /// постоявшая в очереди, доехала бы до координатора уже с исчерпанным потолком.
    ///
    /// Параметров классификации инициатора тут нет: из авто-ходов и system-directive
    /// ветка не вызывается (см. `if (!auto && !systemDirective)` в `SendMessageAsync`),
    /// и аргументы были бы всегда `false`. Классификация инициатора текущего хода для
    /// штаба доставляется в шаге 2г через `StartTeamWorkAsync` (оба места записи —
    /// `SendDirectAsync` и `chats_send` — уезжают вместе со штабом) и закрывается
    /// там, а не здесь. Это сознательное расхождение с первоначальной посылкой плана
    /// §5(3) («инициатор доставляется аргументом того же хука»): точки разные, до
    /// очереди и старта хода, поэтому отдельный хук был бы лишним (см. также
    /// MAJOR 2 ревью 69ce2cb8, этап 4 шаг 2в).
    /// </summary>
    void OnHumanInput(string sessionId);

    /// <summary>
    /// §5(3) №13. Асинхронный крючок «человек написал в чат» — возврат из стадии
    /// «ждёт решения» обычным сообщением (M3). Стадию возвращаем ДО очереди, по тем же
    /// правилам, что решение по карточке, — иначе текст человека упирался бы в гейты стадии.
    /// </summary>
    Task OnHumanInputAsync(string sessionId);

    /// <summary>
    /// §5(3) №14. «Ход задал вопрос» — ASK-карточка посреди хода. В интервью это раунд,
    /// в волне — гашение отсечек сторожа (ожидание человека не зависание). Не терминал —
    /// шиной не доставляется, поэтому отдельный крючок.
    /// </summary>
    Task OnAskQuestionStabAsync(string sessionId);

    /// <summary>
    /// §5(3) №11. «Восстановить режим после миграции» — minor волны 3: если мигрировали
    /// посреди план-фазы на провайдера без поддержки «План», селектор режима заблокирован
    /// (SavedMode висит), а ход уже идёт не в план-режиме. Та же деградация «молча остаёмся
    /// в прежнем режиме», что и EnterPlanPhaseMode на входе в план-фазу.
    /// </summary>
    void RestoreUserMode(string sessionId);

    /// <summary>
    /// §5(4) TeamPlanningInFlight. Запрос «у сессии есть уважительная причина не считаться
    /// зависшей» — планировщик штаба живёт до 300 с без CLI-прогона, и sweep активной
    /// сессии не должен мигать Finished посреди планирования. Формулировка максимально
    /// безликая: не «штаб планирует», а «у сессии есть уважительная причина», чтобы
    /// завтра туда же встала вторая вертикаль с той же потребностью.
    /// </summary>
    bool IsSessionBusy(string sessionId);
}
