namespace ClaudeHomeServer.Services.Spend;

// Шва чтения расхода владельца (детский режим, шаг KM-B5a): «сегодня» и «этот месяц» в
// долларах для одного владельца. Потребитель (проверка бюджета ребёнка, KM-B5c/B5d)
// вертикаль ClaudeHomeServer.Spend не видит — сборка Spend динамический модуль (ADR-014,
// сценарий Б), все её швы живут в Core (тот же порядок, что у ISpendFeatureReader).
// Шва ОПЦИОНАЛЬНА: при выключенной подсистеме Spend (гейт Subsystems:spend:Enabled /
// DynamicModules.spend.Enabled) Register не вызывается, швы нет (`null` у потребителя) —
// это законно, решение «бюджет не проверить» принимает потребитель (fail-closed, KM-B5c).
//
// «Сегодня» и «месяц» — календарные даты ТАЙМЗОНЫ, которую передаёт вызывающий
// (параметр timeZone), а не UTC: запись в 23:30 Europe/Moscow принадлежит этой московской
// дате, даже когда её UTC-дата другая (в сторе все отметки времени — UTC, пересчёт
// делает читатель). Детский бюджет обязан резать день так же, как он режется у человека,
// а не по серверному UTC.
//
// Источник — существующий SpendStore: детальные записи SpendRecord последних Spend:DetailDays
// дней + дневные агрегаты DailySpendRow за более старые. Ходы чатов, one-shot и TTS пишут в один
// стор (TtsController), поэтому читатель НЕ фильтрует по Source. Складывается только USD:
// CostRub и CostCredits — отдельные валюты, нигде со долларами не складываются (SpendRecord).
// Записи без цены (CostUsd null) и с нечисловой ценой (NaN/∞ — сбой CLI) в сумму не входят.
//
// Дневные агрегаты не несут времени суток: их дата — UTC-день, он относится локальному
// окну по своей UTC-дате (граница месяца по свёрнутым дням — нижняя оценка, точность
// даёт детальный окно; для «сегодня» это несущественно: текущий день никогда не свёрнут).
public interface IOwnerSpendReader
{
    // Сумма CostUsd записей владельца, чья дата в таймзоне timeZone — сегодняшняя дата
    // этой таймзоны. Ошибка чтения стора — исключение наружу из швы: решение «бюджет не
    // проверить» принимает потребитель (KM-B5c, fail-closed).
    decimal TodayUsd(string ownerId, TimeZoneInfo timeZone);

    // Сумма CostUsd записей владельца, чья дата в таймзоне timeZone попадает в текущий
    // календарный месяц этой таймзоны.
    decimal MonthUsd(string ownerId, TimeZoneInfo timeZone);
}
