// Живёт рядом с CHAT_COLUMN_W, потому что решает ту же задачу — это запрос центра
// к раскладке, когда чата ещё нет. Раздатчику места (useCenterOffset) нельзя давать
// в этом состоянии CHAT_COLUMN_W: он зарезервирует под несуществующую ленту вдвое
// больше, чем занимает заставка, свободного запаса не увидит и компенсацию перекоса
