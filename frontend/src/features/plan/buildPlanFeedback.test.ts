import { describe, it, expect } from 'vitest';
import { buildPlanFeedback, PLAN_FEEDBACK_FOOTER } from './buildPlanFeedback';

// Контракт «Разделы без замечаний согласованы»: одни и те же слова независимо от
// реализации — их видит и планировщик, и пользователь, и тест на согласованную
// картину ответа
const FOOTER = PLAN_FEEDBACK_FOOTER;

describe('buildPlanFeedback', () => {
  it('пустой список замечаний → только строка о согласованных разделах', () => {
    expect(buildPlanFeedback([], [])).toBe(FOOTER);
  });

  it('одно замечание без цитаты — заголовок, текст и подвал', () => {
    const out = buildPlanFeedback(
      [{ anchorHeading: 'Контекст', text: 'Уточнить вводные.' }],
      ['Контекст'],
    );
    expect(out).toBe(`Раздел «Контекст» → Уточнить вводные.\n\n${FOOTER}`);
  });

  it('замечание с цитатой добавляет строку «> цитата» после «заголовок → текст»', () => {
    const out = buildPlanFeedback(
      [
        {
          anchorHeading: 'Решение',
          text: 'не сходится с ADR-007',
          quote: 'выбираем DeepSeek',
        },
      ],
      ['Решение'],
    );
    expect(out).toBe(
      `Раздел «Решение» → не сходится с ADR-007\n> выбираем DeepSeek\n\n${FOOTER}`,
    );
  });

  it('два замечания на разных разделах идут в порядке плана', () => {
    const out = buildPlanFeedback(
      [
        { anchorHeading: 'Проверка', text: 'добавить интеграционный сценарий' },
        { anchorHeading: 'Контекст', text: 'ссылка на источник' },
      ],
      ['Контекст', 'Проверка'],
    );
    expect(out).toBe(
      [
        'Раздел «Контекст» → ссылка на источник',
        '',
        'Раздел «Проверка» → добавить интеграционный сценарий',
        '',
        FOOTER,
      ].join('\n'),
    );
  });

  it('два замечания на одном разделе идут подряд, через пустую строку', () => {
    const out = buildPlanFeedback(
      [
        { anchorHeading: 'Границы', text: 'не упомянули мобилу', quote: 'узкое место' },
        { anchorHeading: 'Границы', text: 'что с локальной моделью?' },
      ],
      ['Границы'],
    );
    expect(out).toBe(
      [
        'Раздел «Границы» → не упомянули мобилу',
        '> узкое место',
        '',
        'Раздел «Границы» → что с локальной моделью?',
        '',
        FOOTER,
      ].join('\n'),
    );
  });

  it('замечание на отсутствующий в плане заголовок попадает в конец', () => {
    const out = buildPlanFeedback(
      [
        { anchorHeading: 'Известный', text: 'ок' },
        { anchorHeading: 'Опечатка', text: 'что это?' },
      ],
      ['Известный'],
    );
    expect(out).toBe(
      [
        'Раздел «Известный» → ок',
        '',
        'Раздел «Опечатка» → что это?',
        '',
        FOOTER,
      ].join('\n'),
    );
  });

  it('разделы без замечаний упоминаются только подвалом', () => {
    // Явное покрытие требования: «разделы без замечаний попадают в строку согласованы»
    const out = buildPlanFeedback(
      [{ anchorHeading: 'Только этот', text: 'правка' }],
      ['Не тронут 1', 'Только этот', 'Не тронут 2'],
    );
    expect(out).toContain(FOOTER);
    expect(out).not.toContain('Не тронут 1');
    expect(out).not.toContain('Не тронут 2');
    expect(out).toContain('Только этот');
  });

  it('пустая цитата после trim не добавляется в вывод', () => {
    const out = buildPlanFeedback(
      [{ anchorHeading: 'Шапка', text: 'правка', quote: '   ' }],
      ['Шапка'],
    );
    expect(out).toBe(`Раздел «Шапка» → правка\n\n${FOOTER}`);
    expect(out).not.toContain('>');
  });

  it('два замечания на одноимённые разделы идут в разных группах с подписью «(N-й)»', () => {
    // План с одинаковыми заголовками: у первого «Тесты» anchorIndex=0, у второго — 1.
    // Подписи должны различать их как «(1-й)» и «(2-й)» независимо от того, где
    // заголовки стоят в документе — порядковый номер ВНУТРИ одноимённых, а не в DOM
    const out = buildPlanFeedback(
      [
        { anchorHeading: 'Тесты', anchorIndex: 0, text: 'интеграция на месте' },
        { anchorHeading: 'Тесты', anchorIndex: 1, text: 'добавить UI-сценарий' },
      ],
      ['Контекст', 'Тесты', 'Дизайн', 'Тесты', 'Границы'],
    );
    expect(out).toBe(
      [
        'Раздел «Тесты» (1-й) → интеграция на месте',
        '',
        'Раздел «Тесты» (2-й) → добавить UI-сценарий',
        '',
        FOOTER,
      ].join('\n'),
    );
  });

  it('у одноимённых заголовков с ОДНИМ замечанием суффикс «(N-й)» не висит', () => {
    // Дубли заголовков в ПЛАНЕ есть, но замечание — только на одном; «(1-й)» у
    // единственного раздела был бы шумом, как и раньше у неповторяющихся заголовков
    const out = buildPlanFeedback(
      [{ anchorHeading: 'Тесты', anchorIndex: 1, text: 'один-единственный' }],
      ['Тесты', 'Дизайн', 'Тесты'],
    );
    expect(out).toBe(`Раздел «Тесты» → один-единственный\n\n${FOOTER}`);
    expect(out).not.toContain('(1-й)');
  });

  it('два замечания на РАЗНЫЕ одноимённые разделы, не подряд идущие, нумеруются среди одноимённых', () => {
    // План с тремя «Тесты» на DOM-позициях 0, 2, 4. Замечания оставлены на
    // втором и третьем: anchorIndex берётся из useHeadings, occurrence-based —
    // 1 и 2. Если бы суффикс считал по DOM-индексу, вышло бы «(3-й)»/«(5-й)» —
    // не совпадало бы с реальным числом одноимённых разделов в плане.
    const out = buildPlanFeedback(
      [
        { anchorHeading: 'Тесты', anchorIndex: 1, text: 'средний Тесты' },
        { anchorHeading: 'Тесты', anchorIndex: 2, text: 'последний Тесты' },
      ],
      ['Тесты', 'Дизайн', 'Тесты', 'Границы', 'Тесты'],
    );
    expect(out).toContain('Раздел «Тесты» (2-й) → средний Тесты');
    expect(out).toContain('Раздел «Тесты» (3-й) → последний Тесты');
    // Больше трёх «Тесты» в этом плане нет; «(4-й)»/«(5-й)» были бы ошибкой
    expect(out).not.toContain('(4-й)');
    expect(out).not.toContain('(5-й)');
  });

  it('разные заголовки идут в исходном порядке, внутри заголовка — по occurrence', () => {
    // Два «Тесты» и один отдельный раздел между ними: общая сортировка держит
    // позицию заголовка первой в плане (по firstPos в headingOrder), а внутри —
    // упорядочивает occurrence по возрастанию
    const out = buildPlanFeedback(
      [
        { anchorHeading: 'Границы', anchorIndex: 0, text: 'не мобилы' },
        { anchorHeading: 'Тесты', anchorIndex: 1, text: 'для второй Тесты' },
        { anchorHeading: 'Тесты', anchorIndex: 0, text: 'для первой Тесты' },
      ],
      ['Тесты', 'Дизайн', 'Тесты', 'Границы'],
    );
    expect(out).toBe(
      [
        'Раздел «Тесты» (1-й) → для первой Тесты',
        '',
        'Раздел «Тесты» (2-й) → для второй Тесты',
        '',
        'Раздел «Границы» → не мобилы',
        '',
        FOOTER,
      ].join('\n'),
    );
  });

  it('два разных anchorIndex одного заголовка, без anchorIndexAnchor omitted, контекст один и тот же — суффикс по факту', () => {
    // Поломанный случай: anchorIndex опущен у одной из двух записей на «Тесты» →
    // трактуется как 0 → уникальный набор индексов для этого заголовка = {0, 1}
    // → «(N-й)» показывается
    const out = buildPlanFeedback(
      [
        { anchorHeading: 'Тесты', text: 'без индекса', },
        { anchorHeading: 'Тесты', anchorIndex: 1, text: 'со вторым индексом' },
      ],
      ['Тесты', 'Дизайн', 'Тесты'],
    );
    expect(out).toContain('Раздел «Тесты» (1-й) → без индекса');
    expect(out).toContain('Раздел «Тесты» (2-й) → со вторым индексом');
  });
});
