using ClaudeHomeServer.Services.Llm.Claude;

namespace ClaudeHomeServer.Services.Prompts;

/// <summary>
/// Директива добивания оборванного сабагента. Форма и тон — как у цикла «до готово»
/// (OmoPrompts.WorkLoopContinuation): системная директива с номером попытки и явной
/// легализацией честной остановки, чтобы модель не изображала готовность ради выхода.
///
/// Почему добивание адресовано координатору, а не самому агенту: канал «сообщение живому
/// сабагенту» есть только у CLI (текст приезжает агенту как «The coordinator sent a message
/// while you were working…»), у бэкенда своего входа в него нет. Ровно так обрыв и лечили
/// вручную — координатор дослал агенту сообщение, и тот продолжил с того же места (контекст
/// агента цел, факт 8 разбора — см. SubagentRunLog).
/// </summary>
public static class SubagentPrompts
{
    public static string ResumeTruncated(SubagentRunPassport run, int attempt, int max)
    {
        var who = string.IsNullOrWhiteSpace(run.Description)
            ? run.AgentType ?? run.AgentId
            : $"{run.AgentType ?? "агент"} — {run.Description}";
        var where = string.IsNullOrWhiteSpace(run.LastTool)
            ? "на вызове инструмента"
            : $"после вызова инструмента {run.LastTool}";

        return $"""
            [СИСТЕМНАЯ ДИРЕКТИВА — ОБРЫВ САБАГЕНТА {attempt}/{max}]
            Сабагент «{who}» (id {run.AgentId}) замолчал посреди работы: он остановился {where},
            получил результат и не продолжил. Отчёта он НЕ давал — то, что от него пришло,
            это обрывок, а не итог.

            ТРЕБУЕТСЯ СЕЙЧАС:
            - Дошли ему сообщение с просьбой продолжить с того места, где он остановился,
              и довести работу до отчёта (его контекст цел, работа не потеряна).
            - Не отвечает или запустить его заново нечем — доделай его часть сам либо
              перезапусти агента с той же постановкой.
            - Не выдавай его обрывок за готовый результат и не подводи по нему итог.

            Если работа встала на препятствии, которое без человека не решить, — честно опиши
            блокер обычным текстом и остановись: это законное завершение хода, а не провал.
            """;
    }
}
