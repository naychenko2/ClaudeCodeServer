// Хвост S0 (фронт): препроцессинг вики-ссылок не трогает содержимое ```/~~~заборов и
// inline-`…`-кода — тот же контракт, что у бэкенда (NotesService.CodeMask): «ссылка/тег»
// считается только вне кода. Окружение node: проверяется чистая функция препроцессинга.

import { describe, it, expect } from 'vitest';
import { preprocessNotes } from './MarkdownViewer';

const pre = (md: string) => preprocessNotes(md, 0).text;

describe('preprocessNotes: [[…]] вне кода переписывается, внутри кода — нет', () => {
  it('ссылка вне кода → wikilink:', () => {
    const out = pre('См. [[Проект/Страница]].');
    expect(out).toContain('[Проект/Страница](wikilink:');
    expect(out).not.toContain('[[Проект/Страница]]');
  });

  it('ссылка внутри ```-забора остаётся как есть', () => {
    const md = ['До.', '```cs', 'В коде: [[Проект/Страница]]', '```', 'После.'].join('\n');
    expect(pre(md)).toBe(md);
  });

  it('ссылка внутри ~~~-забора остаётся как есть', () => {
    const md = ['~~~', '[[Проект/Страница]]', '~~~'].join('\n');
    expect(pre(md)).toBe(md);
  });

  it('ссылка внутри inline-кода остаётся как есть', () => {
    expect(pre('Пример синтаксиса: `[[Проект/Страница]]`.')).toBe('Пример синтаксиса: `[[Проект/Страница]]`.');
  });

  it('незакрытый забор глушит остаток файла', () => {
    const md = ['```', '[[Проект/Страница]]'].join('\n');
    expect(pre(md)).toBe(md);
  });

  it('забор закрывает только свой маркер: ``` внутри ```` — не закрытие', () => {
    const md = ['````', '```', '[[Проект/Страница]]', '```', '````', 'После: [[Живая]]'].join('\n');
    const out = pre(md);
    expect(out).toContain('[[Проект/Страница]]');   // всё ещё внутри внешнего забора
    expect(out).toContain('[Живая](wikilink:');     // после закрытого забора — живая ссылка
  });

  it('info-string с бэктиком — не открытие забора (CommonMark, как на бэкенде)', () => {
    expect(pre('```cs `пример` [[Живая]]')).toContain('[Живая](wikilink:');
  });

  it('смешанный текст: вне кода переписывается, внутри кода — нет', () => {
    const md = ['См. [[Живая]].', '', '```', '[[ВКоде]]', '```', '', 'И `[[Inline]]` тут.'].join('\n');
    const out = pre(md);
    expect(out).toContain('[Живая](wikilink:');
    expect(out).toContain('[[ВКоде]]');
    expect(out).toContain('`[[Inline]]`');
  });
});
