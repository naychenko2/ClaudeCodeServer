// Затравка разбора комментариев к документам — единый текст для обеих кнопок:
// «Разобрать N» в шапке панели комментариев (один документ, путь известен) и
// «Разобрать комментарии» в AI-хабе (всё накопившееся, документы ищет сам AI).
// Протокол разбора у них общий, поэтому и текст один: разойдись он — кнопки вели бы
// себя по-разному на одних и тех же комментариях.

// Ключ модуля MCP, без которого разбор невозможен (notes_annotations/reply/set_status):
// им гейтится подбор персоны — без него она ответит «инструмент недоступен».
export const ANNOTATIONS_TOOL_KEY = 'notes-annotations';

// Что делать с каждым комментарием. Решение по сути: вопрос — ответить, замечание —
// правка документа, но правка только с согласия человека (ответ в тред ничего не ломает,
// а правка .md — ломает, и молча делать её нельзя).
const PROTOCOL = [
  'По каждому реши по сути:',
  '— вопрос → ответь в треде (notes_reply) и закрой комментарий (notes_set_status);',
  '— замечание к тексту → предложи правку, внеси её в документ ТОЛЬКО после моего согласия, потом закрой;',
  '— комментарий-сирота (state orphan или docMissing) не разбирай вслепую: покажи отдельно, я решу.',
].join('\n');

// Разбор одного документа: путь и область известны — искать нечего.
export function docAnnotationsPrompt(scope: string, path: string): string {
  return [
    `Разбери необработанные (open) комментарии документа: path "${path}", scope "${scope}".`,
    'Прочитай их через notes_annotations и сначала покажи список: о чём каждый и что предлагаешь сделать.',
    PROTOCOL,
  ].join('\n');
}

// Разбор всего накопившегося. project — открытый проект (сужаем область до него);
// без него берём все источники владельца.
export function allAnnotationsPrompt(project?: { id: string; name: string }): string {
  return [
    'Собери мои необработанные комментарии к документам: notes_search со status "open" и пустым query — ' +
    'в каждой записи есть annotation.docPath и annotation.docScope.',
    project
      ? `Возьми только документы проекта «${project.name}» (docScope "${project.id}"), остальные не трогай.`
      : 'Бери все источники — и личные заметки, и документы проектов.',
    'Сгруппируй по документам и покажи списком: документ, сколько открытых комментариев, о чём они. ' +
    'Затем разбирай по одному документу за раз, начиная с того, где открытых больше — так ты не утонешь в контексте.',
    PROTOCOL,
    'Если необработанных комментариев нет — так и скажи, ничего не выдумывай.',
  ].join('\n');
}
