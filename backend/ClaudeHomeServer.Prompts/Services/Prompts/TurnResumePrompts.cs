namespace ClaudeHomeServer.Services.Prompts;

/// <summary>
/// Промпты авто-возобновления ходов, оборванных рестартом сервера (фича turn-auto-resume).
/// Голос и формат — как у соседних промптов (SubagentPrompts/OmoPrompts): прямая
/// системная директива агенту, по-русски, без обвязки.
/// </summary>
public static class TurnResumePrompts
{
    /// <summary>
    /// Директива продолжения хода, оборванного рестартом сервера. Транскрипт ход
    /// пережил (цел на диске), поэтому агенту не нужно начинать заново: он проверяет
    /// результат последнего действия (чтобы не повторять вслепую то, что могло уже
    /// выполниться) и продолжает задачу с того же места.
    /// </summary>
    public static string ServerRestartResume() =>
        "Сервер был перезапущен посреди твоего хода, транскрипт цел. Сначала проверь результат " +
        "последнего действия — не повторяй вслепую то, что могло уже выполниться; затем продолжи задачу.";
}
