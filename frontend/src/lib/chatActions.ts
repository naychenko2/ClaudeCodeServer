// Что скрыто, пока пользователь не трогал глазик. Показывать все восемь кнопок
// сразу нельзя — ряд и карточка распухнут; наружу выведено то, чем пользуются чаще,
// остальное лежит в меню и достаётся оттуда одним кликом по глазику.
//
// Наборы РАЗНЫЕ, потому что места разные по смыслу: в списке чат перебирают
// (поднять нужный, промаркировать, выкинуть лишний), а в открытом чате уже
// работают — там важнее пометить тему и видеть, что чат временный.

