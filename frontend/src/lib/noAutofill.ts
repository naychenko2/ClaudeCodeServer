/**
 * Разметка однострочного поля, которому автозаполнение не нужно.
 *
 * Chrome на Android вешает полосу автозаполнения (пароли, карты, адреса) над клавиатурой
 * на ЛЮБОЙ однострочный input, а `autocomplete="off"` игнорирует умышленно — так решили в
 * самом Chrome ещё в 2014-м. Единственный рычаг, который он слушает, — классификация поля:
 * поля поиска автозаполнением не трогаются (проверено на планшете). Отсюда `type="search"`
 * у поля, куда вводят имя папки или название задачи.
 *
 * Роль возвращаем явно: без неё скринридер объявил бы «поле поиска» там, где вводят название
 * заметки. Формально ARIA для `type="search"` роль `textbox` не разрешает — осознанный размен:
 * человеку с озвучкой важнее правда о поле, чем чистота по букве спецификации.
 *
 * Нативный крестик очистки, который WebKit рисует у полей поиска, погашен глобальным
 * правилом в index.css — вид поля задаёт дизайн-система.
 *
 * Поля на примитивах TextField/IconField размечаются сами (см. Field.tsx); эта константа —
 * для сырых input, написанных мимо дизайн-системы.
 */
export const NO_AUTOFILL = { type: 'search', role: 'textbox', autoComplete: 'off' } as const;
