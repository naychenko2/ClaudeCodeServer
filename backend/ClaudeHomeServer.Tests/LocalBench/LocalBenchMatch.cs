namespace ClaudeHomeServer.Tests.LocalBench;

/// <summary>
/// Вторая метрика замера: совпал ли выбор места с ЭТАЛОНОМ банка — живыми данными
/// продукта (реально выбранный голос персоны, реально стоящий значок, проставленный
/// в трекере приоритет).
///
/// Считается ОТДЕЛЬНО от валидности и намеренно: валидность отвечает на вопрос «соблюдён
/// ли формат», совпадение — «разумен ли выбор». Это разные вопросы с разной ценой ошибки,
/// и сведи их в одно число — место с безупречным форматом и случайными ответами стало бы
/// неотличимо от годного.
///
/// Оракул контракта об эталоне не знает вовсе: он судит формат и обязан остаться
/// независимым — иначе правка банка меняла бы вердикт по валидности.
/// </summary>
public enum LocalBenchMatchKind
{
    /// <summary>Эталона у кейса нет — в знаменатель совпадения кейс не идёт.</summary>
    NoReference,

    /// <summary>Выбор совпал с эталоном.</summary>
    Match,

    /// <summary>Выбор с эталоном разошёлся. Что это значит — зависит от силы эталона.</summary>
    Mismatch,
}

/// <summary>
/// Сила эталона места: ОТ НЕЁ ЗАВИСИТ, как читать несовпадение, и потому она объявляется
/// местом явно, а не угадывается по числам.
/// </summary>
public enum LocalBenchReferenceStrength
{
    /// <summary>
    /// Эталон однозначен: верный ответ ровно один, и несовпадение — ошибка места.
    /// Так у <c>task-dedup</c> (тот же id либо null) и у <c>persona-voice</c>, где
    /// сверяется пол голоса: женской персоне мужской голос — не «иное мнение».
    /// </summary>
    Exact,

    /// <summary>
    /// Эталон — ОДИН ИЗ верных ответов: у значка проекта, фона и приоритета задачи
    /// разумных вариантов несколько, и совпадение работает нижней границей качества.
    /// Несовпадение здесь означает «нужен взгляд человека», а не «ошибка»: сверху
    /// метрика не ограничена, и читать её приговором нельзя.
    /// </summary>
    LowerBound,
}

/// <summary>Вердикт сравнения одного кейса с эталоном. <paramref name="Detail"/> — что именно разошлось.</summary>
public sealed record LocalBenchMatch(LocalBenchMatchKind Kind, string? Detail = null)
{
    /// <summary>Эталона у кейса нет: кейс не идёт в знаменатель совпадения.</summary>
    public static readonly LocalBenchMatch None = new(LocalBenchMatchKind.NoReference);

    public static LocalBenchMatch Same(string? detail = null) =>
        new(LocalBenchMatchKind.Match, detail);

    public static LocalBenchMatch Differs(string detail) =>
        new(LocalBenchMatchKind.Mismatch, detail);
}

/// <summary>
/// Как сверять место с эталоном: сила эталона и сам сличитель — ОДНОЙ записью.
///
/// Связаны они намеренно: разъехавшись, они дали бы подпись «несовпадение — ошибка» под
/// числом, которое считалось по эталону-одному-из-многих, и таблицу прочитали бы
/// приговором там, где её читать приговором нельзя.
///
/// <paramref name="What"/> — что именно сверяется («голос», «приоритет», «значок»):
/// печатается в сводке, потому что «совпадение 12/20» само по себе не говорит, чего
/// именно совпадение.
/// </summary>
/// <param name="Compare">
/// Сличитель: кейс и ВСЕ его ходы — против эталона банка. Работает сырыми ответами через
/// ПРОДУКТОВЫЕ разборы, как и оракул: выход сервиса он бы увидел уже после молчаливой
/// деградации, а деградацию и надо мерить.
/// </param>
public sealed record LocalBenchReference(
    LocalBenchReferenceStrength Strength,
    string What,
    Func<LocalBenchCase, LocalBenchTurns, LocalBenchMatch> Compare);
