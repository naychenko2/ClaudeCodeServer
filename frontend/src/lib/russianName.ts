// Дательный падеж имени собеседника — для подписей вида «Написать Вере…».
// Склоняем только однозначные случаи по окончанию; неоднозначное (мягкий знак: Игорь →
// Игорю, но Любовь → Любови), составное или смешанное имя возвращает null — вызывающий
// тогда пишет фразу без имени: лучше без имени, чем с ошибкой.
// Имя без кириллицы (Claude, DeepSeek, GLM 5) не склоняется и возвращается как есть.

const CYR = /[а-яё]/i;
const CONSONANT_END = /[бвгджзклмнпрстфхцчшщ]$/i;

// Родительный падеж имени — для подписей вида «своё у Веры: 1 секция».
// Тот же подход, что у dativeName ниже: склоняем только однозначные окончания;
// неоднозначное, составное или смешанное имя возвращает null — вызывающий
// тогда оставляет именительный (фраза с несклонённым именем хуже грамматически,
// но не теряет смысла). Имя без кириллицы возвращается как есть.
export function genitiveName(name: string): string | null {
  const n = name.trim();
  if (!n) return null;
  if (!CYR.test(n)) return n;
  // Только одно слово из кириллицы с заглавной: «ГР», «Вера Павловна», «Bot-Вера» — мимо
  if (!/^[А-ЯЁ][а-яё]+$/.test(n)) return null;
  if (/[ьй]$/.test(n)) return `${n.slice(0, -1)}я`;  // Игорь → Игоря, Дмитрий → Дмитрия
  if (/я$/.test(n)) return `${n.slice(0, -1)}и`;     // Мария → Марии, Таня → Тани
  if (/а$/.test(n)) {
    // Орфография окончания: после г,к,х,ж,ч,ш,щ — «и», иначе «ы»
    const prev = n.slice(-2, -1);
    return `${n.slice(0, -1)}${/[гкхжчшщ]/.test(prev) ? 'и' : 'ы'}`; // Вера→Веры, Ольга→Ольги
  }
  if (/е$/.test(n)) return `${n.slice(0, -1)}я`;     // Сергей → Сергея, Алексей → Алексея
  if (CONSONANT_END.test(n)) return `${n}а`;         // Глеб → Глеба, Александр → Александра
  return null; // «о», «у» и прочие — неоднозначно
}

export function dativeName(name: string): string | null {
  const n = name.trim();
  if (!n) return null;
  if (!CYR.test(n)) return n;
  // Только одно слово из кириллицы с заглавной: «ГР», «Вера Павловна», «Bot-Вера» — мимо
  if (!/^[А-ЯЁ][а-яё]+$/.test(n)) return null;
  if (/ия$/.test(n)) return n.slice(0, -1) + 'и';   // Мария → Марии, София → Софии
  if (/[ая]$/.test(n)) return n.slice(0, -1) + 'е'; // Вера → Вере, Илья → Илье
  if (/й$/.test(n)) return n.slice(0, -1) + 'ю';    // Дмитрий → Дмитрию, Сергей → Сергею
  if (CONSONANT_END.test(n)) return n + 'у';        // Олег → Олегу, Максим → Максиму
  return null;
}
